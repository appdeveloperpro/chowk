create table if not exists public.user_notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  article_id bigint references public.articles(id) on delete cascade,
  title text not null,
  message text not null default '',
  action text not null default '',
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists user_notifications_inbox_idx
  on public.user_notifications(user_id,is_read,created_at desc);

alter table public.user_notifications enable row level security;
grant select on public.user_notifications to authenticated;
revoke update on public.user_notifications from authenticated;
grant update(is_read) on public.user_notifications to authenticated;

drop policy if exists "Users read own newsroom notifications" on public.user_notifications;
create policy "Users read own newsroom notifications"
on public.user_notifications for select to authenticated
using (user_id=(select auth.uid()));

drop policy if exists "Users update own newsroom notifications" on public.user_notifications;
create policy "Users update own newsroom notifications"
on public.user_notifications for update to authenticated
using (user_id=(select auth.uid()))
with check (user_id=(select auth.uid()));

create or replace function public.chowk_notify_article_workflow()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  article_author uuid;
begin
  select author_id into article_author from public.articles where id=new.article_id;
  if article_author is null then return new; end if;

  if new.to_status in ('changes_requested','rejected','published','scheduled','withdrawn','submitted')
     and new.actor_id is distinct from article_author then
    insert into public.user_notifications(user_id,article_id,title,message,action)
    values (
      article_author,new.article_id,
      case new.to_status
        when 'changes_requested' then 'Changes requested'
        when 'rejected' then 'Story rejected'
        when 'published' then 'Story published'
        when 'scheduled' then 'Story scheduled'
        when 'withdrawn' then 'Story withdrawn'
        else 'Story returned to review'
      end,
      new.note,new.action
    );
  end if;

  if new.to_status='submitted' then
    insert into public.user_notifications(user_id,article_id,title,message,action)
    select article.assigned_to,new.article_id,'New story awaiting moderation',new.note,new.action
    from public.articles article
    where article.id=new.article_id
      and article.assigned_to is not null
      and article.assigned_to is distinct from article_author;
  end if;

  if new.to_status='moderator_review' then
    insert into public.user_notifications(user_id,article_id,title,message,action)
    select new.actor_id,new.article_id,'Story assigned for moderation',new.note,new.action
    where new.actor_id is not null;
  elsif new.to_status='editor_review' then
    insert into public.user_notifications(user_id,article_id,title,message,action)
    select profile.id,new.article_id,'Story ready for editorial review',new.note,new.action
    from public.profiles profile
    where profile.role in ('editor','publisher')
      and profile.id is distinct from article_author;
  end if;
  return new;
end;
$$;

create or replace function public.chowk_validate_location_hierarchy()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  parent_type text;
begin
  if new.parent_id is null then
    if new.location_type <> 'state' then
      raise exception 'Only a state can be a top-level location' using errcode='23514';
    end if;
    return new;
  end if;
  if new.parent_id=new.id then
    raise exception 'A location cannot be its own parent' using errcode='23514';
  end if;
  select location_type into parent_type
  from public.locations
  where id=new.parent_id and is_active;
  if parent_type is null then
    raise exception 'Choose an active parent location' using errcode='23514';
  end if;
  if not (
    (new.location_type='zone' and parent_type='state')
    or (new.location_type='district' and parent_type in ('state','zone'))
    or (new.location_type='city' and parent_type='district')
    or (new.location_type='coverage_area' and parent_type in ('district','city'))
  ) then
    raise exception 'The selected parent location has an invalid hierarchy level' using errcode='23514';
  end if;
  if tg_op='UPDATE' and exists (
    with recursive descendants(id,visited) as (
      select old.id,array[old.id]
      union all
      select child.id,descendants.visited || child.id
      from descendants
      join public.locations child on child.parent_id=descendants.id
      where not child.id=any(descendants.visited)
    )
    select 1 from descendants where id=new.parent_id
  ) then
    raise exception 'A location cannot be moved beneath one of its descendants' using errcode='23514';
  end if;
  return new;
end;
$$;

drop function if exists public.chow_notify_article_workflow();
drop function if exists public.chow_validate_location_hierarchy();

drop trigger if exists chowk_locations_validate_hierarchy on public.locations;
create trigger chowk_locations_validate_hierarchy
before insert or update on public.locations
for each row execute function public.chowk_validate_location_hierarchy();

drop trigger if exists chowk_article_workflow_notifications on public.article_workflow_events;
create trigger chowk_article_workflow_notifications
after insert on public.article_workflow_events
for each row execute function public.chowk_notify_article_workflow();

create or replace function public.chowk_process_due_articles()
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  changed_count integer;
begin
  perform set_config('chowk.workflow_event_action','scheduled_publication',true);
  perform set_config('chowk.workflow_event_note','Scheduled publication time reached',true);
  with due as (
    update public.articles
    set workflow_status='published',workflow_updated_at=now()
    where workflow_status='scheduled'
      and published_at is not null
      and published_at<=now()
    returning id
  )
  select count(*) into changed_count from due;
  perform set_config('chowk.workflow_event_action','',true);
  perform set_config('chowk.workflow_event_note','',true);
  return changed_count;
end;
$$;
revoke all on function public.chowk_process_due_articles() from public,anon,authenticated;
grant execute on function public.chowk_process_due_articles() to postgres;

do $$
begin
  if exists (select 1 from pg_available_extensions where name='pg_cron') then
    execute 'create extension if not exists pg_cron';
    if not exists (select 1 from cron.job where jobname='chowk-publish-due-articles') then
      perform cron.schedule(
        'chowk-publish-due-articles',
        '* * * * *',
        'select public.chowk_process_due_articles()'
      );
    end if;
  else
    raise notice 'pg_cron is unavailable; enable it and schedule chowk_process_due_articles() every minute.';
  end if;
end;
$$;

