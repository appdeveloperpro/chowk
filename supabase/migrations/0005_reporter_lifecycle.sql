create or replace function public.chowk_submit_reporter_application(
  target_state bigint,
  target_rto bigint,
  target_type bigint,
  accepted_version text,
  accepted_sha256 text,
  signer_name text,
  acceptance_statement text
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  applicant uuid := (select auth.uid());
  published_agreement public.reporter_agreement_versions%rowtype;
  application_id bigint;
begin
  if applicant is null then raise exception 'Sign in required' using errcode = '42501'; end if;
  if not exists (select 1 from public.profiles where id=applicant and role='subscriber') then
    raise exception 'Only a subscriber account can submit a reporter application' using errcode='42501';
  end if;
  select * into published_agreement from public.reporter_agreement_versions
  where status = 'published' for share;
  if not found or accepted_version is distinct from published_agreement.version
      or accepted_sha256 is distinct from published_agreement.sha256 then
    raise exception 'The agreement changed. Review and accept the current version.' using errcode = '23514';
  end if;
  if length(trim(coalesce(signer_name, ''))) < 2
      or length(trim(coalesce(acceptance_statement, ''))) < 10 then
    raise exception 'Enter your full name and explicit agreement acceptance.' using errcode = '22023';
  end if;
  if not exists (select 1 from public.states where id = target_state and is_active) then
    raise exception 'Select an active state' using errcode = '22023';
  end if;
  if not exists (select 1 from public.rto_offices where id = target_rto
      and state_id = target_state and is_active) then
    raise exception 'Select an active RTO in the selected state' using errcode = '22023';
  end if;
  if not exists (select 1 from public.reporter_types where id = target_type and is_active) then
    raise exception 'Select an active reporter type' using errcode = '22023';
  end if;
  insert into public.reporter_applications (
    user_id, state_id, rto_office_id, reporter_type_id, agreement_accepted,
    agreement_version, agreement_sha256, agreement_document_url, agreement_signer_name,
    agreement_acceptance_statement, agreement_accepted_at,
    status
  )
  values (
    applicant, target_state, target_rto, target_type, true,
    published_agreement.version, published_agreement.sha256, published_agreement.document_url,
    trim(signer_name), trim(acceptance_statement), now(), 'pending'
  )
  on conflict (user_id) do update
  set state_id = excluded.state_id,
      rto_office_id = excluded.rto_office_id,
      reporter_type_id = excluded.reporter_type_id,
      agreement_accepted = true,
      agreement_version = excluded.agreement_version,
      agreement_sha256 = excluded.agreement_sha256,
      agreement_document_url = excluded.agreement_document_url,
      agreement_signer_name = excluded.agreement_signer_name,
      agreement_acceptance_statement = excluded.agreement_acceptance_statement,
      agreement_accepted_at = now(),
      status = 'pending',
      review_note = '',
      reviewed_by = null,
      reviewed_at = null
  where public.reporter_applications.status = 'rejected'
  returning id into application_id;
  if application_id is null then
    raise exception 'An application already exists and cannot be resubmitted in its current state' using errcode = '23505';
  end if;
  insert into public.reporter_agreement_acceptances (
    application_id, user_id, agreement_version, agreement_sha256, signer_name, acceptance_statement
  )
  values (
    application_id, applicant, published_agreement.version, published_agreement.sha256,
    trim(signer_name), trim(acceptance_statement)
  );
  return application_id;
end;
$$;
revoke all on function public.chowk_submit_reporter_application(bigint,bigint,bigint,text,text,text,text) from public, anon;
grant execute on function public.chowk_submit_reporter_application(bigint,bigint,bigint,text,text,text,text) to authenticated;

create or replace function public.chowk_accept_current_reporter_agreement(
  accepted_version text,
  accepted_sha256 text,
  signer_name text,
  acceptance_statement text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  applicant uuid := (select auth.uid());
  application_row public.reporter_applications%rowtype;
  agreement public.reporter_agreement_versions%rowtype;
begin
  if applicant is null then raise exception 'Sign in required' using errcode='42501'; end if;
  select * into application_row from public.reporter_applications
  where user_id=applicant for update;
  if not found or application_row.status <> 'pending' then
    raise exception 'Only a pending application can accept an updated agreement' using errcode='23514';
  end if;
  select * into agreement from public.reporter_agreement_versions
  where status='published' for share;
  if not found or accepted_version is distinct from agreement.version
      or accepted_sha256 is distinct from agreement.sha256 then
    raise exception 'The agreement changed. Review and accept the current version.' using errcode='23514';
  end if;
  if length(trim(coalesce(signer_name,'')))<2 or length(trim(coalesce(acceptance_statement,'')))<10 then
    raise exception 'Enter your full name and explicit agreement acceptance' using errcode='22023';
  end if;
  update public.reporter_applications set
    agreement_accepted=true,
    agreement_version=agreement.version,
    agreement_sha256=agreement.sha256,
    agreement_document_url=agreement.document_url,
    agreement_signer_name=trim(signer_name),
    agreement_acceptance_statement=trim(acceptance_statement),
    agreement_accepted_at=now()
  where id=application_row.id;
  insert into public.reporter_agreement_acceptances(
    application_id,user_id,agreement_version,agreement_sha256,signer_name,acceptance_statement
  ) values (
    application_row.id,applicant,agreement.version,agreement.sha256,
    trim(signer_name),trim(acceptance_statement)
  );
end;
$$;
revoke all on function public.chowk_accept_current_reporter_agreement(text,text,text,text) from public, anon;
grant execute on function public.chowk_accept_current_reporter_agreement(text,text,text,text) to authenticated;

create or replace function public.chowk_admin_review_reporter_application(
  target_application bigint,
  decision text,
  note text default '',
  signer_name text default '',
  signer_designation text default '',
  signature_accepted boolean default false
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := (select auth.uid());
  application_row public.reporter_applications%rowtype;
  rto public.rto_offices%rowtype;
  state_row public.states%rowtype;
  reporter_type public.reporter_types%rowtype;
  issued_number integer;
  new_code text;
begin
  if actor is null or not (select public.chowk_has_any_role(array['admin', 'super_admin'])) then
    raise exception 'Admin access required' using errcode = '42501';
  end if;
  if decision not in ('approved', 'rejected') then
    raise exception 'Decision must be approved or rejected' using errcode = '22023';
  end if;
  select * into application_row from public.reporter_applications
  where id = target_application for update;
  if not found or application_row.status <> 'pending' then
    raise exception 'Only a pending application can be reviewed' using errcode = '23514';
  end if;
  if decision = 'rejected' and length(trim(coalesce(note, ''))) < 2 then
    raise exception 'A reason is required when rejecting an application' using errcode = '22023';
  end if;
  if decision = 'approved' then
    if not application_row.agreement_accepted or application_row.agreement_version = ''
       or application_row.agreement_sha256 is null or application_row.agreement_accepted_at is null then
      raise exception 'Applicant must accept a versioned reporter agreement' using errcode = '23514';
    end if;
    if length(trim(coalesce(signer_name, ''))) < 2
       or length(trim(coalesce(signer_designation, ''))) < 2
       or not coalesce(signature_accepted, false) then
      raise exception 'Company signer details and signature acceptance are required' using errcode = '22023';
    end if;
    select * into rto from public.rto_offices where id = application_row.rto_office_id and is_active;
    select * into state_row from public.states where id = application_row.state_id and is_active;
    select * into reporter_type from public.reporter_types where id = application_row.reporter_type_id and is_active;
    if rto.id is null or state_row.id is null or reporter_type.id is null or rto.state_id <> state_row.id then
      raise exception 'Application location or reporter type is no longer active' using errcode = '23514';
    end if;
    insert into public.reporter_code_counters(rto_office_id, reporter_type_id)
    values (rto.id, reporter_type.id)
    on conflict do nothing;
    update public.reporter_code_counters set next_number = next_number + 1
    where rto_office_id = rto.id and reporter_type_id = reporter_type.id
    returning next_number - 1 into issued_number;
    if issued_number > 9999 then
      raise exception 'Reporter ID sequence is exhausted for this RTO and reporter type' using errcode = '22003';
    end if;
    new_code := lower(state_row.state_code || rto.rto_code || '-' || reporter_type.type_code || '-' || lpad(issued_number::text, 4, '0'));
    insert into public.reporter_profiles(user_id, reporter_code)
    values (application_row.user_id, new_code)
    on conflict (user_id) do nothing;
    insert into public.reporter_assignments(user_id, rto_office_id, reporter_type_id, assigned_by)
    values (application_row.user_id, rto.id, reporter_type.id, actor);
  end if;
  update public.reporter_applications
  set status = decision,
      review_note = trim(coalesce(note, '')),
      reviewed_by = actor,
      reviewed_at = now(),
      company_signer_name = case when decision = 'approved' then nullif(trim(coalesce(signer_name, '')), '') else null end,
      company_signer_designation = case when decision = 'approved' then nullif(trim(coalesce(signer_designation, '')), '') else null end,
      company_signature_accepted = decision = 'approved' and coalesce(signature_accepted, false),
      company_signed_at = case when decision = 'approved' then now() else null end,
      company_signature_statement = case when decision = 'approved'
        then 'Authorized signer confirms approval under the current Chowk reporter agreement.'
        else null end
  where id = target_application;
  if decision = 'approved' then
    update public.profiles set role = 'reporter' where id = application_row.user_id;
  end if;
end;
$$;
revoke all on function public.chowk_admin_review_reporter_application(bigint,text,text,text,text,boolean) from public, anon;
grant execute on function public.chowk_admin_review_reporter_application(bigint,text,text,text,text,boolean) to authenticated;

create or replace function public.chowk_reporter_status()
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'application', (select to_jsonb(a) || jsonb_build_object(
      'state', jsonb_build_object('id', s.id, 'state_code', s.state_code, 'state_name', s.state_name),
      'rto', jsonb_build_object('id', r.id, 'rto_code', r.rto_code, 'city_name', r.city_name),
      'reporter_type', jsonb_build_object('id', t.id, 'type_code', t.type_code, 'name', t.name),
      'reviewer_name', reviewer.full_name,
      'acceptances', coalesce((
        select jsonb_agg(jsonb_build_object(
          'agreement_version', receipt.agreement_version,
          'agreement_sha256', receipt.agreement_sha256,
          'signer_name', receipt.signer_name,
          'acceptance_statement', receipt.acceptance_statement,
          'accepted_at', receipt.accepted_at
        ) order by receipt.accepted_at desc)
        from public.reporter_agreement_acceptances receipt
        where receipt.application_id=a.id
      ), '[]'::jsonb)
    )
      from public.reporter_applications a
      left join public.states s on s.id = a.state_id
      left join public.rto_offices r on r.id = a.rto_office_id
      left join public.reporter_types t on t.id = a.reporter_type_id
      left join public.profiles reviewer on reviewer.id = a.reviewed_by
      where a.user_id = (select auth.uid())),
    'reporter', (select jsonb_build_object(
      'reporter_code', rp.reporter_code, 'assignments', coalesce((
        select jsonb_agg(jsonb_build_object(
          'id', ra.id, 'effective_from', ra.effective_from, 'effective_to', ra.effective_to,
          'state_name', s.state_name, 'rto_code', ro.rto_code, 'city_name', ro.city_name,
          'type_name', rt.name, 'type_code', rt.type_code
        ) order by ra.effective_from desc)
        from public.reporter_assignments ra
        join public.rto_offices ro on ro.id = ra.rto_office_id
        join public.states s on s.id = ro.state_id
        join public.reporter_types rt on rt.id = ra.reporter_type_id
        where ra.user_id = rp.user_id
      ), '[]'::jsonb))
      from public.reporter_profiles rp where rp.user_id = (select auth.uid())),
    'credentials', coalesce((select jsonb_agg(jsonb_build_object(
      'id', c.id, 'credential_type', c.credential_type, 'reference_code', c.reference_code,
      'status', c.status, 'valid_from', c.valid_from, 'valid_until', c.valid_until,
      'verification_token', c.verification_token, 'scope', c.scope_snapshot
    ) order by c.issued_at desc)
      from public.staff_credentials c
      where c.subject_user_id_snapshot = (select auth.uid())), '[]'::jsonb)
  );
$$;
