create table if not exists public.reporter_designations (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text not null default '',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

insert into public.reporter_designations(name, description, is_active)
select distinct name, description, is_active
from public.reporter_types
on conflict (name) do nothing;

alter table public.reporter_applications
  add column if not exists reporter_designation_id bigint
    references public.reporter_designations(id) on delete restrict;
alter table public.reporter_assignments
  add column if not exists reporter_designation_id bigint
    references public.reporter_designations(id) on delete restrict;

update public.reporter_applications application
set reporter_designation_id = designation.id
from public.reporter_types legacy_type
join public.reporter_designations designation on designation.name = legacy_type.name
where application.reporter_type_id = legacy_type.id
  and application.reporter_designation_id is null;

update public.reporter_assignments assignment
set reporter_designation_id = designation.id
from public.reporter_types legacy_type
join public.reporter_designations designation on designation.name = legacy_type.name
where assignment.reporter_type_id = legacy_type.id
  and assignment.reporter_designation_id is null;

create index if not exists reporter_applications_designation_idx
  on public.reporter_applications(reporter_designation_id);
create index if not exists reporter_assignments_designation_idx
  on public.reporter_assignments(reporter_designation_id);

alter table public.reporter_designations enable row level security;
grant select on public.reporter_designations to anon, authenticated;
grant insert, update, delete on public.reporter_designations to authenticated;
grant usage, select on sequence public.reporter_designations_id_seq to authenticated;

drop policy if exists "Active reporter designations are public" on public.reporter_designations;
create policy "Active reporter designations are public" on public.reporter_designations
for select to anon, authenticated
using (is_active or (select public.chowk_has_any_role(array['admin', 'super_admin'])));
drop policy if exists "Admins manage reporter designations" on public.reporter_designations;
create policy "Admins manage reporter designations" on public.reporter_designations
for all to authenticated
using ((select public.chowk_has_any_role(array['admin', 'super_admin'])))
with check ((select public.chowk_has_any_role(array['admin', 'super_admin'])));

drop trigger if exists chowk_reporter_designations_updated_at on public.reporter_designations;
create trigger chowk_reporter_designations_updated_at before update on public.reporter_designations
