create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  full_name text not null default '',
  phone text,
  role text not null default 'subscriber'
    check (role in ('subscriber', 'reporter', 'editor', 'admin', 'super_admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.articles (
  id bigint generated by default as identity primary key,
  title text not null,
  slug text not null unique,
  excerpt text not null default '',
  content text not null default '',
  category_id bigint references public.categories (id) on delete set null,
  image_url text,
  status text not null default 'draft'
    check (status in ('draft', 'published', 'archived')),
  author_id uuid references public.profiles (id) on delete set null,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists articles_publication_idx
  on public.articles (status, published_at desc);
create index if not exists articles_category_idx
  on public.articles (category_id);

grant usage on schema public to anon, authenticated;

create or replace function public.chowk_set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists chowk_profiles_set_updated_at on public.profiles;
