create or replace function public.chowk_get_contributor_for_profile(target_profile uuid)
returns bigint
language sql
stable
security definer
set search_path = ''
as $$
  select id
  from public.newsroom_contributors
  where profile_id = target_profile
    and is_active
  limit 1;
$$;

create or replace function public.chowk_workspace_create_opinion_story(
  article_title text,
  article_slug text,
  article_excerpt text default '',
  article_content text default '',
  article_category_id bigint default null,
  article_image_url text default null,
  article_video_url text default null,
  article_audio_url text default null,
  article_reporting_location_id bigint default null,
  article_content_type text default 'opinion',
  article_news_priority text default 'routine',
  article_reporting_sources text default '',
  article_reporting_evidence text default '',
  article_contact_status text default null,
  article_contact_notes text default '',
  article_author_disclosure text default '',
  article_breaking_review_note text default '',
  article_thumbnail_url text default null,
  article_thumbnail_alt_text text default '',
  article_thumbnail_credit_line text default '',
  article_thumbnail_license_name text default '',
  article_opinion_contributor_id bigint default null,
  article_opinion_column_name text default '',
  article_conflict_disclosure text default '',
  article_fact_sources text default '',
  article_ai_use_disclosure text default ''
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  saved_id bigint;
  actor uuid := auth.uid();
begin
  if article_content_type in ('opinion', 'editorial')
     and not public.chowk_validate_constrained_content_type(article_content_type, actor) then
    raise exception 'This staff account is not assigned to submit this restricted content type'
      using errcode = '42501';
  end if;

  if article_content_type = 'opinion' then
    if article_opinion_contributor_id is not null
       and not exists (
         select 1
         from public.newsroom_contributors contributor
         where contributor.id = article_opinion_contributor_id
           and contributor.is_active
           and (
             contributor.profile_id = actor
             or exists (
               select 1
               from public.newsroom_content_assignments assignment
               where assignment.profile_id = actor
                 and assignment.article_type_key = 'opinion'
                 and assignment.is_active
                 and (assignment.contributor_id = contributor.id or assignment.contributor_id is null)
                 and assignment.effective_from <= now()
                 and (assignment.effective_to is null or assignment.effective_to >= now())
             )
             or public.chowk_org_user_has_capability('newsroom.opinion.review')
             or public.chowk_org_user_has_capability('newsroom.opinion.publish')
           )
       ) then
      raise exception 'Choose an active contributor assigned to this opinion story'
        using errcode = '42501';
    end if;
  end if;

  saved_id := public.chowk_workspace_create_article_with_asset_thumbnail_v2(
    article_title, article_slug, article_excerpt, article_content, article_category_id,
    article_image_url, article_video_url, article_audio_url, article_reporting_location_id,
    article_content_type, article_news_priority, article_reporting_sources,
    article_reporting_evidence, article_contact_status, article_contact_notes,
    article_author_disclosure, article_breaking_review_note, article_thumbnail_url,
    article_thumbnail_alt_text, article_thumbnail_credit_line, article_thumbnail_license_name
  );

  update public.articles
  set opinion_contributor_id = coalesce(
        article_opinion_contributor_id,
        case when article_content_type = 'opinion'
          then public.chowk_get_contributor_for_profile(actor)
          else null end
      ),
      opinion_column_name = trim(coalesce(article_opinion_column_name, '')),
      conflict_of_interest_disclosure = trim(coalesce(article_conflict_disclosure, '')),
      fact_sources = trim(coalesce(article_fact_sources, '')),
      ai_use_disclosure = trim(coalesce(article_ai_use_disclosure, '')),
      opinion_review_status = case
        when article_content_type = 'opinion' then 'pending_review'
        else 'not_required'
      end
  where id = saved_id;
  return saved_id;
end;
$$;

create or replace function public.chowk_workspace_update_opinion_story(
  target_article bigint,
  article_title text,
  article_slug text,
  article_excerpt text default '',
  article_content text default '',
  article_category_id bigint default null,
  article_image_url text default null,
  article_video_url text default null,
  article_audio_url text default null,
  article_reporting_location_id bigint default null,
  change_reason text default '',
  article_content_type text default 'opinion',
  article_news_priority text default 'routine',
  article_reporting_sources text default '',
  article_reporting_evidence text default '',
  article_contact_status text default null,
  article_contact_notes text default '',
  article_author_disclosure text default '',
  article_breaking_review_note text default '',
  article_thumbnail_url text default null,
  article_thumbnail_alt_text text default '',
  article_thumbnail_credit_line text default '',
  article_thumbnail_license_name text default '',
  article_opinion_contributor_id bigint default null,
  article_opinion_column_name text default '',
  article_conflict_disclosure text default '',
  article_fact_sources text default '',
  article_ai_use_disclosure text default ''
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := auth.uid();
  existing public.articles%rowtype;
begin
  select * into existing
  from public.articles
  where id = target_article
  for update;
  if not found then
    raise exception 'Story not found' using errcode = 'P0002';
  end if;

  if article_content_type in ('opinion', 'editorial')
     and not public.chowk_validate_constrained_content_type(article_content_type, actor)
     and not (existing.content_type = article_content_type
       and public.chowk_org_user_has_capability('newsroom.opinion.review')) then
    raise exception 'This staff account is not assigned to submit or review this restricted content type'
      using errcode = '42501';
  end if;

  perform public.chowk_workspace_update_article_with_asset_thumbnail_v2(
    target_article, article_title, article_slug, article_excerpt, article_content,
    article_category_id, article_image_url, article_video_url, article_audio_url,
    article_reporting_location_id, change_reason, article_content_type,
    article_news_priority, article_reporting_sources, article_reporting_evidence,
    article_contact_status, article_contact_notes, article_author_disclosure,
    article_breaking_review_note, article_thumbnail_url, article_thumbnail_alt_text,
    article_thumbnail_credit_line, article_thumbnail_license_name
  );

  update public.articles
  set opinion_contributor_id = coalesce(
        article_opinion_contributor_id,
        existing.opinion_contributor_id,
        case when article_content_type = 'opinion'
          then public.chowk_get_contributor_for_profile(actor)
          else null end
      ),
      opinion_column_name = trim(coalesce(article_opinion_column_name, '')),
      conflict_of_interest_disclosure = trim(coalesce(article_conflict_disclosure, '')),
      fact_sources = trim(coalesce(article_fact_sources, '')),
      ai_use_disclosure = trim(coalesce(article_ai_use_disclosure, '')),
      opinion_review_status = case
        when article_content_type <> 'opinion' then 'not_required'
        when existing.opinion_review_status in ('approved', 'rejected') then 'pending_review'
        else coalesce(existing.opinion_review_status, 'pending_review')
      end
  where id = target_article;
end;
$$;

