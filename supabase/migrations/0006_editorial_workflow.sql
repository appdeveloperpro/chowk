create or replace function public.chowk_workspace_locations()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  actor uuid := (select auth.uid());
  actor_role text;
begin
  select role into actor_role from public.profiles where id=actor;
  if actor is null or actor_role not in ('reporter','moderator','editor','publisher','admin','super_admin') then
    raise exception 'Newsroom role required' using errcode='42501';
  end if;
  return coalesce((
    select jsonb_agg(jsonb_build_object(
      'id',location.id,'name',location.name,'location_type',location.location_type,
      'parent_id',location.parent_id
    ) order by location.location_type,location.name)
    from public.locations location
    where location.is_active
      and (
        actor_role not in ('reporter','moderator')
        or public.chowk_user_covers_location(actor,location.id)
      )
  ),'[]'::jsonb);
end;
$$;
revoke all on function public.chowk_workspace_locations() from public, anon;
grant execute on function public.chowk_workspace_locations() to authenticated;

create or replace function public.chowk_workspace_create_article(
  article_title text,
  article_slug text,
  article_excerpt text default '',
  article_content text default '',
  article_category_id bigint default null,
  article_image_url text default null,
  article_video_url text default null,
  article_audio_url text default null,
  article_reporting_location_id bigint default null
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := (select auth.uid());
  actor_role text;
  new_article_id bigint;
begin
  select role into actor_role from public.profiles where id = actor;
  if actor is null or actor_role not in ('reporter', 'editor', 'admin', 'super_admin') then
    raise exception 'Newsroom role required to create a story' using errcode='42501';
  end if;
  if length(trim(coalesce(article_title,''))) < 8 or length(trim(coalesce(article_title,''))) > 240
     or length(trim(coalesce(article_slug,''))) < 3 or length(trim(coalesce(article_slug,''))) > 240 then
    raise exception 'Enter a headline (8-240 characters) and valid URL slug' using errcode='22023';
  end if;
  if article_content is null or length(trim(article_content)) < 50 then
    raise exception 'Story content must contain at least 50 characters' using errcode='22023';
  end if;
  if article_category_id is not null and not exists (
    select 1 from public.categories where id=article_category_id and is_active
  ) then
    raise exception 'Choose an active category' using errcode='22023';
  end if;
  if article_reporting_location_id is not null and not exists (
    select 1 from public.locations where id=article_reporting_location_id and is_active
  ) then raise exception 'Choose an active reporting location' using errcode='22023'; end if;
  if actor_role in ('reporter','editor') and article_reporting_location_id is null then
    raise exception 'Choose a reporting location before creating a newsroom story' using errcode='22023';
  end if;
  if actor_role='reporter' and (
    not exists (select 1 from public.reporter_profiles where user_id=actor)
    or not exists (select 1 from public.reporter_assignments where user_id=actor and effective_to is null)
    or article_reporting_location_id is null
    or not public.chowk_user_covers_location(actor,article_reporting_location_id)
  ) then
    raise exception 'A current reporter ID, assignment, and matching coverage are required to file a story' using errcode='42501';
  end if;
  insert into public.articles(
    title,slug,excerpt,content,category_id,image_url,video_url,audio_url,reporting_location_id,status,workflow_status,author_id
  ) values (
    trim(article_title),trim(article_slug),coalesce(article_excerpt,''),article_content,
    article_category_id,nullif(trim(coalesce(article_image_url,'')), ''),
    nullif(trim(coalesce(article_video_url,'')),''),nullif(trim(coalesce(article_audio_url,'')), ''),
    article_reporting_location_id,'draft','draft',actor
  ) returning id into new_article_id;
  insert into public.article_workflow_events(
    article_id,actor_id,actor_name,actor_role,action,from_status,to_status,note
  ) select new_article_id,actor,coalesce(full_name,''),actor_role,'created',null,'draft','Draft created'
    from public.profiles where id=actor;
  return new_article_id;
end;
$$;

create or replace function public.chowk_workspace_update_article(
  target_article bigint,
  article_title text,
  article_slug text,
  article_excerpt text default '',
  article_content text default '',
  article_category_id bigint default null,
  article_image_url text default null,
  article_video_url text default null,
  article_audio_url text default null,
  article_reporting_location_id bigint default null,
  change_reason text default ''
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := (select auth.uid());
  actor_role text;
  article_row public.articles%rowtype;
begin
  if actor is null then raise exception 'Sign in required' using errcode='42501'; end if;
  select role into actor_role from public.profiles where id=actor;
  select * into article_row from public.articles where id=target_article for update;
  if not found then raise exception 'Story not found' using errcode='P0002'; end if;
  if actor_role='reporter' and not (
    article_row.author_id=actor and article_row.workflow_status in ('draft','changes_requested')
  ) then raise exception 'Reporters can edit only their own drafts or stories returned for changes' using errcode='42501'; end if;
  if actor_role='moderator' and article_row.workflow_status <> 'moderator_review' then
    raise exception 'Moderators can edit only stories in moderator review' using errcode='42501';
  end if;
  if actor_role='moderator' and (
    article_row.reporting_location_id is null
    or not public.chowk_user_covers_location(actor,article_row.reporting_location_id)
    or (article_row.assigned_to is not null and article_row.assigned_to<>actor)
  ) then
    raise exception 'This story is outside your assigned coverage or assigned to another moderator' using errcode='42501';
  end if;
  if actor_role='editor' and (
    article_row.workflow_status not in ('draft','editor_review','scheduled','published')
    or (article_row.workflow_status='draft' and article_row.author_id<>actor)
  ) then
    raise exception 'Editors can edit only stories in the editor queue or published stories' using errcode='42501';
  end if;
  if actor_role='publisher' and article_row.workflow_status <> 'editor_review' then
    raise exception 'Publishers can edit only stories in the editor queue' using errcode='42501';
  end if;
  if actor_role in ('admin','super_admin') and length(trim(coalesce(change_reason,''))) < 2 then
    raise exception 'An admin edit requires an audit reason' using errcode='22023';
  end if;
  if actor_role is null or actor_role not in ('reporter','moderator','editor','publisher','admin','super_admin') then
    raise exception 'Newsroom role required' using errcode='42501';
  end if;
  if length(trim(coalesce(article_title,''))) < 8 or length(trim(coalesce(article_title,''))) > 240
     or length(trim(coalesce(article_slug,''))) < 3 or length(trim(coalesce(article_slug,''))) > 240
     or length(trim(coalesce(article_content,''))) < 50 then
    raise exception 'Check headline, URL slug, and story content' using errcode='22023';
  end if;
  if article_category_id is not null and not exists (
    select 1 from public.categories where id=article_category_id and is_active
  ) then raise exception 'Choose an active category' using errcode='22023'; end if;
  if article_reporting_location_id is not null and not exists (
    select 1 from public.locations where id=article_reporting_location_id and is_active
  ) then raise exception 'Choose an active reporting location' using errcode='22023'; end if;
  if actor_role in ('reporter','moderator','editor','publisher')
     and article_reporting_location_id is null then
    raise exception 'Choose a reporting location before saving this story' using errcode='22023';
  end if;
  if actor_role='reporter' and (
    article_row.reporting_location_id is distinct from article_reporting_location_id
    or not public.chowk_user_covers_location(actor,article_reporting_location_id)
  ) then
    raise exception 'Reporter story location must remain within your assigned coverage' using errcode='42501';
  end if;
  if actor_role='moderator' and (
    article_reporting_location_id is null
    or not public.chowk_user_covers_location(actor,article_reporting_location_id)
  ) then
    raise exception 'The story location must remain within your assigned coverage' using errcode='42501';
  end if;
  insert into public.article_revisions(
    article_id,changed_by,title,slug,excerpt,content,category_id,image_url,video_url,audio_url,reporting_location_id,
    workflow_status,change_reason
  ) values (
    article_row.id,actor,article_row.title,article_row.slug,article_row.excerpt,
    article_row.content,article_row.category_id,article_row.image_url,article_row.video_url,article_row.audio_url,
    article_row.reporting_location_id,
    article_row.workflow_status,trim(coalesce(change_reason,''))
  );
  update public.articles set
    title=trim(article_title),slug=trim(article_slug),excerpt=coalesce(article_excerpt,''),
    content=article_content,category_id=article_category_id,
    image_url=nullif(trim(coalesce(article_image_url,'')),''),
    video_url=nullif(trim(coalesce(article_video_url,'')),''),
    audio_url=nullif(trim(coalesce(article_audio_url,'')),''),
    reporting_location_id=article_reporting_location_id,
    workflow_updated_at=now()
  where id=target_article;
end;
$$;

create or replace function public.chowk_workspace_transition_article(
  target_article bigint,
  requested_action text,
  action_note text default '',
  scheduled_for timestamptz default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := (select auth.uid());
  actor_name_value text;
  actor_role text;
  article_row public.articles%rowtype;
  next_status text;
begin
  if actor is null then raise exception 'Sign in required' using errcode='42501'; end if;
  select full_name,role into actor_name_value,actor_role
  from public.profiles where id=actor;
  select * into article_row from public.articles where id=target_article for update;
  if not found then raise exception 'Story not found' using errcode='P0002'; end if;
  if actor_role='moderator' and (
    article_row.reporting_location_id is null
    or not public.chowk_user_covers_location(actor,article_row.reporting_location_id)
    or (article_row.assigned_to is not null and article_row.assigned_to<>actor)
  ) then
    raise exception 'This story is outside your assigned coverage or assigned to another moderator' using errcode='42501';
  end if;

  if requested_action='submit' and actor_role in ('reporter','editor')
     and article_row.author_id=actor
     and article_row.workflow_status in ('draft','changes_requested') then
    next_status := 'submitted';
  elsif requested_action='withdraw' and actor_role='reporter'
     and article_row.author_id=actor
     and article_row.workflow_status in ('submitted','moderator_review','changes_requested') then
    next_status := 'withdrawn';
  elsif requested_action='restore_withdrawn' and actor_role='reporter'
     and article_row.author_id=actor
     and article_row.workflow_status='withdrawn' then
    next_status := 'draft';
  elsif requested_action='delete_withdrawn' and actor_role='reporter'
     and article_row.author_id=actor
     and article_row.workflow_status='withdrawn' then
    next_status := 'archived';
  elsif requested_action='start_review' and actor_role='moderator'
     and article_row.workflow_status='submitted' then
    next_status := 'moderator_review';
  elsif requested_action='send_to_editor' and actor_role='moderator'
     and article_row.workflow_status='moderator_review' then
    next_status := 'editor_review';
  elsif requested_action='request_changes' and actor_role in ('moderator','editor')
     and ((actor_role='moderator' and article_row.workflow_status='moderator_review')
       or (actor_role='editor' and article_row.workflow_status='editor_review')) then
    next_status := 'changes_requested';
  elsif requested_action='reject' and actor_role in ('moderator','editor')
     and ((actor_role='moderator' and article_row.workflow_status='moderator_review')
       or (actor_role='editor' and article_row.workflow_status='editor_review')) then
    next_status := 'rejected';
  elsif requested_action='publish' and actor_role in ('editor','publisher')
     and article_row.workflow_status in ('editor_review','scheduled') then
    next_status := 'published';
  elsif requested_action='schedule' and actor_role in ('editor','publisher')
     and article_row.workflow_status in ('editor_review','scheduled')
     and scheduled_for is not null and scheduled_for > now() then
    next_status := 'scheduled';
  elsif requested_action='unschedule' and actor_role in ('editor','publisher')
     and article_row.workflow_status='scheduled' then
    next_status := 'editor_review';
  elsif requested_action='reopen_rejected' and actor_role in ('admin','super_admin')
     and article_row.workflow_status='rejected' then
    next_status := 'submitted';
  elsif requested_action='publish' and actor_role in ('admin','super_admin')
     and article_row.workflow_status not in ('withdrawn','archived','rejected') then
    if length(trim(coalesce(action_note,''))) < 2 then
      raise exception 'Admin publication requires an override reason' using errcode='22023';
    end if;
    next_status := 'published';
  elsif requested_action='archive' and actor_role in ('editor','publisher','admin','super_admin')
     and article_row.workflow_status in ('published','scheduled','rejected') then
    next_status := 'archived';
  else
    raise exception 'This role cannot perform that action in the current story state' using errcode='42501';
  end if;

  if requested_action in ('request_changes','reject') and length(trim(coalesce(action_note,''))) < 2 then
    raise exception 'Add a review note to return or reject this story' using errcode='22023';
  end if;
  if actor_role in ('admin','super_admin') and length(trim(coalesce(action_note,''))) < 2 then
    raise exception 'Admin workflow overrides require an audit reason' using errcode='22023';
  end if;
  if requested_action='submit' and (
    length(trim(coalesce(article_row.title,''))) < 8
    or length(trim(coalesce(article_row.content,''))) < 50
  ) then
    raise exception 'Complete the headline and story content before submitting' using errcode='22023';
  end if;
  if requested_action='submit' and actor_role='reporter' and (
    not exists (select 1 from public.reporter_profiles where user_id=actor)
    or not exists (select 1 from public.reporter_assignments where user_id=actor and effective_to is null)
    or article_row.reporting_location_id is null
    or not public.chowk_user_covers_location(actor,article_row.reporting_location_id)
  ) then
    raise exception 'Current reporter assignment and coverage are required to submit this story' using errcode='42501';
  end if;
  if requested_action='submit' and actor_role='editor' and (
    article_row.reporting_location_id is null
    or not exists (
      select 1 from public.locations
      where id=article_row.reporting_location_id and is_active
    )
  ) then
    raise exception 'Choose an active reporting location before submitting this story' using errcode='22023';
  end if;
  perform set_config('chowk.workflow_event_action', requested_action, true);
  perform set_config('chowk.workflow_event_note', trim(coalesce(action_note,'')), true);
  update public.articles set
    workflow_status=next_status,
    status=case when next_status in ('published','scheduled') then 'published'
      when next_status='archived' then 'archived' else 'draft' end,
    published_at=case when next_status='published' then now()
      when next_status='scheduled' then scheduled_for
      when requested_action='unschedule'
        or next_status in ('archived','withdrawn','rejected','changes_requested') then null
      else published_at end,
    submitted_at=case when requested_action in ('submit','reopen_rejected') then now() else submitted_at end,
    review_note=case when requested_action in ('request_changes','reject') then trim(action_note)
      when requested_action in ('submit','send_to_editor','publish','schedule','unschedule','reopen_rejected') then ''
      else review_note end,
    assigned_to=case
      when requested_action='submit' and actor_role='reporter' then (
        with recursive target_path(id,parent_id,visited) as (
          select location.id,location.parent_id,array[location.id]
          from public.locations location
          where location.id=article_row.reporting_location_id and location.is_active
          union all
          select parent.id,parent.parent_id,target_path.visited || parent.id
          from target_path
          join public.locations parent on parent.id=target_path.parent_id and parent.is_active
          where not parent.id=any(target_path.visited)
        )
        select moderator.id
        from public.profiles moderator
        join public.user_coverage_assignments coverage on coverage.user_id=moderator.id
        where moderator.role='moderator'
          and coverage.valid_from<=now()
          and (coverage.valid_to is null or coverage.valid_to>now())
          and (
            coalesce(coverage.zone_id,coverage.district_id,coverage.city_id,coverage.coverage_area_id)
              = article_row.reporting_location_id
            or (
              coverage.include_descendants
              and coalesce(coverage.zone_id,coverage.district_id,coverage.city_id,coverage.coverage_area_id)
                in (select id from target_path)
            )
          )
        order by coverage.valid_from desc,moderator.id
        limit 1
      )
      when next_status='moderator_review' then actor
      else null
    end,
    workflow_updated_at=now()
  where id=target_article;
  perform set_config('chowk.workflow_event_action', '', true);
  perform set_config('chowk.workflow_event_note', '', true);
end;
$$;

