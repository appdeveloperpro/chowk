create or replace function public.chowk_workspace_create_article_with_metadata(
  article_title text,
  article_slug text,
  article_excerpt text default '',
  article_content text default '',
  article_category_id bigint default null,
  article_image_url text default null,
  article_video_url text default null,
  article_audio_url text default null,
  article_reporting_location_id bigint default null,
  article_content_type text default 'news',
  article_news_priority text default 'routine',
  article_reporting_sources text default '',
  article_reporting_evidence text default '',
  article_contact_status text default null,
  article_contact_notes text default '',
  article_author_disclosure text default '',
  article_breaking_review_note text default ''
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := (select auth.uid());
  actor_role text;
  saved_id bigint;
begin
  select role into actor_role from public.profiles where id = actor;
  if article_news_priority not in ('routine', 'breaking')
     or (article_contact_status is not null and article_contact_status not in (
       'contacted', 'no_response', 'unable_to_reach', 'not_applicable'
     ))
     or length(coalesce(article_reporting_sources, '')) > 5000
     or length(coalesce(article_reporting_evidence, '')) > 5000
     or length(coalesce(article_contact_notes, '')) > 2000
     or length(coalesce(article_author_disclosure, '')) > 2000
     or length(coalesce(article_breaking_review_note, '')) > 1000 then
    raise exception 'Check the editorial type, priority, reporting notes, and disclosure values'
      using errcode = '22023';
  end if;
  if article_news_priority = 'breaking'
     and length(trim(coalesce(article_breaking_review_note, ''))) < 10 then
    raise exception 'Explain why this story needs Breaking review (at least 10 characters)'
      using errcode = '22023';
  end if;
  if not exists (
    select 1 from public.article_types
    where key = article_content_type and is_active
      and (not editorial_only or actor_role in ('editor', 'admin', 'super_admin')
        or public.chowk_org_user_has_capability('newsroom.articles.editorial'))
  ) then
    raise exception 'Choose an active article type available to your newsroom role'
      using errcode = '42501';
  end if;

  saved_id := public.chowk_workspace_create_article(
    article_title, article_slug, article_excerpt, article_content, article_category_id,
    article_image_url, article_video_url, article_audio_url, article_reporting_location_id
  );
  perform set_config('chow.breaking_review_update', 'on', true);
  update public.articles set
    content_type = article_content_type,
    news_priority = article_news_priority,
    reporting_sources = trim(coalesce(article_reporting_sources, '')),
    reporting_evidence = trim(coalesce(article_reporting_evidence, '')),
    contact_status = article_contact_status,
    contact_notes = trim(coalesce(article_contact_notes, '')),
    author_disclosure = trim(coalesce(article_author_disclosure, '')),
    breaking_review_status = case when article_news_priority = 'breaking' then 'requested' else 'none' end,
    breaking_review_note = case when article_news_priority = 'breaking'
      then trim(coalesce(article_breaking_review_note, '')) else '' end,
    breaking_reviewed_by = null,
    breaking_reviewed_at = null,
    breaking_expires_at = null
  where id = saved_id;
  perform set_config('chow.breaking_review_update', '', true);
  return saved_id;
end;
$$;

create or replace function public.chowk_workspace_update_article_with_metadata(
  target_article bigint,
  article_title text,
  article_slug text,
  article_excerpt text default '',
  article_content text default '',
  article_category_id bigint default null,
  article_image_url text default null,
  article_video_url text default null,
  article_audio_url text default null,
  article_reporting_location_id bigint default null,
  change_reason text default '',
  article_content_type text default 'news',
  article_news_priority text default 'routine',
  article_reporting_sources text default '',
  article_reporting_evidence text default '',
  article_contact_status text default null,
  article_contact_notes text default '',
  article_author_disclosure text default '',
  article_breaking_review_note text default ''
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := (select auth.uid());
  actor_role text;
  existing_article public.articles%rowtype;
begin
  select role into actor_role from public.profiles where id = actor;
  select * into existing_article from public.articles where id = target_article for update;
  if not found then raise exception 'Story not found' using errcode = 'P0002'; end if;
  if article_news_priority not in ('routine', 'breaking')
     or (article_contact_status is not null and article_contact_status not in (
       'contacted', 'no_response', 'unable_to_reach', 'not_applicable'
     ))
     or length(coalesce(article_reporting_sources, '')) > 5000
     or length(coalesce(article_reporting_evidence, '')) > 5000
     or length(coalesce(article_contact_notes, '')) > 2000
     or length(coalesce(article_author_disclosure, '')) > 2000
     or length(coalesce(article_breaking_review_note, '')) > 1000 then
    raise exception 'Check the editorial type, priority, reporting notes, and disclosure values'
      using errcode = '22023';
  end if;
  if article_news_priority = 'breaking'
     and (
       existing_article.news_priority <> 'breaking'
       or existing_article.breaking_review_status in ('none', 'rejected')
     )
     and length(trim(coalesce(article_breaking_review_note, ''))) < 10 then
    raise exception 'Explain why this story needs Breaking review (at least 10 characters)'
      using errcode = '22023';
  end if;
  if not exists (
    select 1 from public.article_types
    where key = article_content_type
      and (
        is_active
        or existing_article.content_type = article_content_type
      )
      and (not editorial_only or actor_role in ('editor', 'admin', 'super_admin')
        or public.chowk_org_user_has_capability('newsroom.articles.editorial'))
  ) then
    raise exception 'Choose an active article type available to your newsroom role'
      using errcode = '42501';
  end if;

  perform public.chowk_workspace_update_article(
    target_article, article_title, article_slug, article_excerpt, article_content,
    article_category_id, article_image_url, article_video_url, article_audio_url,
    article_reporting_location_id, change_reason
  );

  perform set_config('chow.breaking_review_update', 'on', true);
  update public.articles set
    content_type = article_content_type,
    news_priority = article_news_priority,
    reporting_sources = trim(coalesce(article_reporting_sources, '')),
    reporting_evidence = trim(coalesce(article_reporting_evidence, '')),
    contact_status = article_contact_status,
    contact_notes = trim(coalesce(article_contact_notes, '')),
    author_disclosure = trim(coalesce(article_author_disclosure, '')),
    breaking_review_status = case
      when article_news_priority = 'routine' then 'none'
      when existing_article.news_priority <> 'breaking'
        or existing_article.breaking_review_status in ('none', 'rejected') then 'requested'
      else existing_article.breaking_review_status
    end,
    breaking_review_note = case
      when article_news_priority = 'routine' then ''
      when existing_article.news_priority <> 'breaking'
        or existing_article.breaking_review_status in ('none', 'rejected')
        then trim(coalesce(article_breaking_review_note, ''))
      else existing_article.breaking_review_note
    end,
    breaking_reviewed_by = case
      when article_news_priority = 'routine'
        or existing_article.news_priority <> 'breaking'
        or existing_article.breaking_review_status in ('none', 'rejected') then null
      else existing_article.breaking_reviewed_by
    end,
    breaking_reviewed_at = case
      when article_news_priority = 'routine'
        or existing_article.news_priority <> 'breaking'
        or existing_article.breaking_review_status in ('none', 'rejected') then null
      else existing_article.breaking_reviewed_at
    end,
    breaking_expires_at = case
      when article_news_priority = 'routine'
        or existing_article.news_priority <> 'breaking'
        or existing_article.breaking_review_status in ('none', 'rejected') then null
      else existing_article.breaking_expires_at
    end
  where id = target_article;
  perform set_config('chow.breaking_review_update', '', true);
end;
$$;

create or replace function public.chowk_workspace_review_breaking_request(
  target_article bigint,
  approve_request boolean,
  validity_hours integer default 6,
  review_note text default ''
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := (select auth.uid());
  article_row public.articles%rowtype;
begin
  select * into article_row from public.articles where id = target_article for update;
  if not found then raise exception 'Story not found' using errcode = 'P0002'; end if;
  if not public.chowk_org_can_access_article(
    'newsroom.articles.publish', article_row.author_id, article_row.assigned_to,
    article_row.workflow_status, article_row.reporting_location_id
  ) then
    raise exception 'Publishing permission is required to review a Breaking request'
      using errcode = '42501';
  end if;
  if article_row.news_priority <> 'breaking'
     or article_row.breaking_review_status <> 'requested' then
    raise exception 'This story has no pending Breaking request' using errcode = '22023';
  end if;
  if approve_request and (validity_hours is null or validity_hours < 1 or validity_hours > 24) then
    raise exception 'Breaking approval must expire within 1 to 24 hours' using errcode = '22023';
  end if;
  if length(trim(coalesce(review_note, ''))) < 2 then
    raise exception 'Add a short reason when approving or rejecting a Breaking request'
      using errcode = '22023';
  end if;

  perform set_config('chow.breaking_review_update', 'on', true);
  update public.articles set
    breaking_review_status = case when approve_request then 'approved' else 'rejected' end,
    breaking_review_note = trim(coalesce(review_note, '')),
    breaking_reviewed_by = actor,
    breaking_reviewed_at = now(),
    breaking_expires_at = case when approve_request
      then now() + make_interval(hours => validity_hours) else null end
  where id = target_article;
  perform set_config('chow.breaking_review_update', '', true);
end;
$$;

