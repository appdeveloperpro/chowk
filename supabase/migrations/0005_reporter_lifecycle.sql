create or replace function public.chowk_admin_assign_reporter(
  target_user uuid, target_rto bigint, target_type bigint
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := (select auth.uid());
  rto public.rto_offices%rowtype;
  state_row public.states%rowtype;
  reporter_type public.reporter_types%rowtype;
  current_code text;
  sequence_number integer;
  generated_code text;
begin
  if actor is null or not (select public.chowk_has_any_role(array['admin','super_admin'])) then
    raise exception 'Admin access required' using errcode='42501';
  end if;
  if not exists(select 1 from public.profiles where id=target_user and role='reporter') then
    raise exception 'Target user is not an approved reporter' using errcode='23514';
  end if;
  select * into rto from public.rto_offices where id=target_rto and is_active;
  select * into state_row from public.states where id=rto.state_id and is_active;
  select * into reporter_type from public.reporter_types where id=target_type and is_active;
  if rto.id is null or state_row.id is null or reporter_type.id is null then
    raise exception 'Select an active state, RTO and reporter type' using errcode='22023';
  end if;
  select reporter_code into current_code from public.reporter_profiles where user_id=target_user for update;
  if current_code is null then
    insert into public.reporter_code_counters(rto_office_id, reporter_type_id)
    values(rto.id, reporter_type.id) on conflict do nothing;
    update public.reporter_code_counters set next_number=next_number+1
    where rto_office_id=rto.id and reporter_type_id=reporter_type.id
    returning next_number-1 into sequence_number;
    if sequence_number > 9999 then raise exception 'Reporter ID sequence exhausted' using errcode='22003'; end if;
    generated_code := lower(state_row.state_code || rto.rto_code || '-' || reporter_type.type_code || '-' || lpad(sequence_number::text,4,'0'));
    insert into public.reporter_profiles(user_id, reporter_code) values(target_user, generated_code);
  end if;
  update public.reporter_assignments set effective_to=now()
  where user_id=target_user and effective_to is null;
  insert into public.reporter_assignments(user_id,rto_office_id,reporter_type_id,assigned_by)
  values(target_user,rto.id,reporter_type.id,actor);
end;
$$;
