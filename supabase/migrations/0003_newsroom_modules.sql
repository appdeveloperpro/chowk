create table if not exists public.locations (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  location_type text not null check (location_type in ('state', 'zone', 'district', 'city', 'coverage_area')),
  parent_id bigint references public.locations (id) on delete set null,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.reporter_types (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text not null default '',
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.reporter_applications (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references public.profiles (id) on delete cascade,
  reporter_type_id bigint references public.reporter_types (id) on delete set null,
  location_id bigint references public.locations (id) on delete set null,
  agreement_accepted boolean not null default false,
  agreement_version text not null default '',
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  review_note text not null default '',
  reviewed_by uuid references public.profiles (id) on delete set null,
  reviewed_at timestamptz,
  company_signer_name text,
  company_signer_designation text,
  company_signature_accepted boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.live_streams (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null default '',
  youtube_video_id text,
  youtube_url text,
  status text not null default 'scheduled' check (status in ('scheduled', 'live', 'ended')),
  scheduled_at timestamptz,
  started_at timestamptz,
  ended_at timestamptz,
  created_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.article_reports (
  id bigint generated by default as identity primary key,
  article_id bigint not null references public.articles (id) on delete cascade,
  reporter_id uuid references public.profiles (id) on delete set null,
  reason text not null,
  details text not null default '',
  status text not null default 'open' check (status in ('open', 'resolved', 'dismissed')),
  reviewed_by uuid references public.profiles (id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  article_id bigint not null references public.articles (id) on delete cascade,
  user_id uuid references public.profiles (id) on delete set null,
  content text not null,
  is_approved boolean not null default false,
  reviewed_by uuid references public.profiles (id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.media_catalog (
  id bigint generated by default as identity primary key,
  media_type text not null check (media_type in ('podcast', 'charcha', 'patrika')),
  title text not null,
  description text not null default '',
  media_url text not null,
  cover_url text,
  episode_label text,
  duration_seconds integer check (duration_seconds is null or duration_seconds >= 0),
  issue_date date,
  status text not null default 'draft' check (status in ('draft', 'published', 'archived')),
  published_at timestamptz,
  created_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  actor_id uuid references public.profiles (id) on delete set null,
  action text not null,
  table_name text not null,
  record_id text,
  before_data jsonb,
  after_data jsonb,
  created_at timestamptz not null default now()
);

create or replace function public.chowk_admin_review_reporter_application(
  target_application bigint,
  decision text,
  note text default '',
  signer_name text default '',
  signer_designation text default '',
  signature_accepted boolean default false
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor_role text;
  application_row public.reporter_applications%rowtype;
begin
  select role into actor_role from public.profiles where id = (select auth.uid());
  if actor_role is null or actor_role not in ('admin', 'super_admin') then
    raise exception 'Admin access required' using errcode = '42501';
  end if;
  if decision not in ('approved', 'rejected') then
    raise exception 'Decision must be approved or rejected' using errcode = '22023';
  end if;
  select * into application_row
  from public.reporter_applications
  where id = target_application
  for update;
  if not found then
    raise exception 'Application not found' using errcode = 'P0002';
  end if;
  if application_row.status <> 'pending' then
    raise exception 'Only pending applications can be reviewed' using errcode = '23514';
  end if;
  if decision = 'approved' and
      (not application_row.agreement_accepted or application_row.agreement_version = '') then
    raise exception 'Applicant must accept a versioned reporter agreement' using errcode = '23514';
  end if;
  if decision = 'approved' and
      (length(trim(coalesce(signer_name, ''))) < 2
       or length(trim(coalesce(signer_designation, ''))) < 2
       or not coalesce(signature_accepted, false)) then
    raise exception 'Company signer details and signature acceptance are required' using errcode = '22023';
  end if;
  if decision = 'rejected' and length(trim(coalesce(note, ''))) < 2 then
    raise exception 'A reason is required when rejecting an application' using errcode = '22023';
  end if;
  update public.reporter_applications
  set status = decision,
      review_note = coalesce(note, ''),
      reviewed_by = (select auth.uid()),
      reviewed_at = now(),
      company_signer_name = nullif(trim(coalesce(signer_name, '')), ''),
      company_signer_designation = nullif(trim(coalesce(signer_designation, '')), ''),
      company_signature_accepted = coalesce(signature_accepted, false)
  where id = target_application;
  if decision = 'approved' then
    update public.profiles set role = 'reporter' where id = application_row.user_id;
  end if;
end;
$$;

revoke all on function public.chowk_admin_review_reporter_application(bigint, text, text, text, text, boolean) from public, anon;
grant execute on function public.chowk_admin_review_reporter_application(bigint, text, text, text, text, boolean) to authenticated;

