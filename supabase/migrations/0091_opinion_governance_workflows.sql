  add column if not exists conflict_of_interest_disclosure text not null default ''
    check (length(conflict_of_interest_disclosure) <= 5000),
  add column if not exists fact_sources text not null default ''
    check (length(fact_sources) <= 5000),
  add column if not exists ai_use_disclosure text not null default ''
    check (length(ai_use_disclosure) <= 2000),
  add column if not exists opinion_review_status text not null default 'not_required'
    check (opinion_review_status in (
      'not_required', 'draft', 'pending_review', 'approved', 'revisions_requested', 'rejected'
    )),
  add column if not exists opinion_reviewer_id uuid
    references public.profiles(id) on delete set null;

