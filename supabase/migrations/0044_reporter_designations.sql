create or replace function public.chowk_admin_set_reporter_designation(
  target_application bigint,
  target_designation bigint
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := (select auth.uid());
  application_row public.reporter_applications%rowtype;
  assignment_row public.reporter_assignments%rowtype;
begin
  if actor is null or not (select public.chowk_has_any_role(array['admin', 'super_admin'])) then
    raise exception 'Admin access required' using errcode = '42501';
  end if;

  select * into application_row
  from public.reporter_applications
  where id = target_application
  for update;
  if not found or application_row.status not in ('pending', 'needs_information', 'approved') then
    raise exception 'Designation can only be assigned while the application is awaiting approval or agreement issuance'
      using errcode = '23514';
  end if;
  if application_row.service_agreement_issue_id is not null or exists (
    select 1
    from public.reporter_service_agreement_issues
    where application_id = application_row.id
  ) then
    raise exception 'This reporter already has an issued agreement. Their designation cannot be changed without changing the agreement.'
      using errcode = '23514';
  end if;
  if not exists (
    select 1 from public.reporter_designations
    where id = target_designation and is_active
  ) then
    raise exception 'Choose an active reporter designation' using errcode = '22023';
  end if;

  update public.reporter_applications
  set reporter_designation_id = target_designation
  where id = application_row.id
    and reporter_designation_id is distinct from target_designation;

  if application_row.status <> 'approved' then
    return;
  end if;

  select * into assignment_row
  from public.reporter_assignments
  where user_id = application_row.user_id and effective_to is null
  for update;
  if not found then
    raise exception 'The approved reporter has no current assignment to update'
      using errcode = '23514';
  end if;
  if assignment_row.reporter_designation_id = target_designation then
    return;
  end if;

  update public.reporter_assignments
  set effective_to = clock_timestamp()
  where id = assignment_row.id;

  insert into public.reporter_assignments(
    user_id, rto_office_id, reporter_type_id, reporter_designation_id,
    effective_from, assigned_by
  )
  values (
    assignment_row.user_id,
    assignment_row.rto_office_id,
    assignment_row.reporter_type_id,
    target_designation,
    clock_timestamp(),
    actor
  );
end;
$$;

revoke all on function public.chowk_admin_set_reporter_designation(bigint, bigint) from public, anon;
grant execute on function public.chowk_admin_set_reporter_designation(bigint, bigint) to authenticated;

create or replace function public.chowk_require_designation_before_reporter_approval()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.status = 'approved' and (
    new.reporter_designation_id is null
    or not exists (
      select 1
      from public.reporter_designations
      where id = new.reporter_designation_id and is_active
    )
  ) then
    raise exception 'Choose an active reporter designation before approving the application'
      using errcode = '23514';
  end if;
  return new;
end;
$$;

drop trigger if exists chowk_require_designation_before_reporter_approval
  on public.reporter_applications;
create trigger chowk_require_designation_before_reporter_approval
before update of status on public.reporter_applications
for each row execute function public.chowk_require_designation_before_reporter_approval();

create or replace function public.chowk_guard_issued_reporter_designation()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_app_id bigint;
  application_designation bigint;
begin
  if tg_table_name = 'reporter_applications' then
    if new.reporter_designation_id is distinct from old.reporter_designation_id
        and exists (
          select 1
          from public.reporter_service_agreement_issues
          where application_id = old.id
        ) then
      raise exception 'A reporter designation cannot be changed after a service agreement has been issued'
        using errcode = '23514';
    end if;
    return new;
  end if;

  select application.id, application.reporter_designation_id
  into target_app_id, application_designation
  from public.reporter_applications application
  where application.user_id = new.user_id
  order by application.created_at desc
  limit 1;

  if new.reporter_designation_id is null and application_designation is not null then
    new.reporter_designation_id := application_designation;
  end if;

  if target_app_id is not null
      and new.reporter_designation_id is distinct from application_designation
      and exists (
        select 1
        from public.reporter_service_agreement_issues issue
        where issue.application_id = target_app_id
      ) then
    raise exception 'A reporter designation cannot be changed after a service agreement has been issued'
      using errcode = '23514';
  end if;
  return new;
end;
$$;

drop trigger if exists chowk_guard_issued_reporter_application_designation
  on public.reporter_applications;
create trigger chowk_guard_issued_reporter_application_designation
before update of reporter_designation_id on public.reporter_applications
for each row execute function public.chowk_guard_issued_reporter_designation();

drop trigger if exists chowk_guard_issued_reporter_assignment_designation
  on public.reporter_assignments;
create trigger chowk_guard_issued_reporter_assignment_designation
before insert or update of reporter_designation_id on public.reporter_assignments
for each row execute function public.chowk_guard_issued_reporter_designation();

create or replace function public.chowk_admin_publish_reporter_service_agreement(target_agreement bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  agreement_row public.reporter_service_agreement_versions%rowtype;
  remaining_tokens text;
begin
  if (select auth.uid()) is null
      or not (select public.chowk_has_any_role(array['admin', 'super_admin'])) then
    raise exception 'Admin access required' using errcode = '42501';
  end if;
  select * into agreement_row
  from public.reporter_service_agreement_versions
  where id = target_agreement and status in ('draft', 'published')
  for update;
  if not found then
    raise exception 'Draft service agreement not found' using errcode = 'P0002';
  end if;
  if agreement_row.template_content is null then
    raise exception 'Only personalized service-agreement templates can be published'
      using errcode = '23514';
  end if;
  if not exists (
    select 1 from public.reporter_organization_profile
    where id is true and is_verified
  ) then
    raise exception 'Verify the organization legal profile before publishing personalized service agreements'
      using errcode = '23514';
  end if;
  if length(trim(agreement_row.template_content)) < 1000
      or agreement_row.template_content ~ '\[[^]]+\]' then
    raise exception 'Replace all square-bracket terms and complete the agreement before publishing'
      using errcode = '23514';
  end if;
  if position('{{reporter.designation}}' in agreement_row.template_content) = 0 then
    raise exception 'Add {{reporter.designation}} to the service agreement so the assigned position is included'
      using errcode = '23514';
  end if;
  remaining_tokens := regexp_replace(
    agreement_row.template_content,
    '\{\{(agreement\.date|company\.(entity_type|legal_name|official_email|official_phone|registered_address|registration_number|trade_name|website_url)|reporter\.(city|designation|email|full_name|phone|reporter_code|rto|state|father_first_name|father_last_name|permanent_address|permanent_address_line1|permanent_address_line2|permanent_address_city|permanent_address_district|permanent_address_state|permanent_address_postal_code|date_of_birth|mobile_number))\}\}',
    '',
    'g'
  );
  if remaining_tokens ~ '\{\{[^}]+\}\}' then
    raise exception 'The service agreement contains an unknown or unsupported server template field'
      using errcode = '23514';
  end if;
  update public.reporter_service_agreement_versions
  set status = 'archived'
  where status = 'published' and id <> target_agreement;
  update public.reporter_service_agreement_versions
  set status = 'published', published_by = (select auth.uid()), published_at = now()
  where id = target_agreement;
end;
$$;

revoke all on function public.chowk_admin_publish_reporter_service_agreement(bigint) from public, anon;
grant execute on function public.chowk_admin_publish_reporter_service_agreement(bigint) to authenticated;

create or replace function public.chowk_admin_review_reporter_application_with_designation(
  target_application bigint,
  decision text,
  note text,
  signer_name text,
  signer_designation text,
  signature_accepted boolean,
  requested_fields jsonb,
  target_designation bigint
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if decision = 'approved' then
    if target_designation is null then
      raise exception 'Choose a reporter designation before approving the application'
        using errcode = '22023';
    end if;
    perform public.chowk_admin_set_reporter_designation(target_application, target_designation);
  end if;

  perform public.chowk_admin_review_reporter_application(
    target_application,
    decision,
    note,
    signer_name,
    signer_designation,
    signature_accepted,
    requested_fields
  );
end;
$$;

revoke all on function public.chowk_admin_review_reporter_application_with_designation(
  bigint, text, text, text, text, boolean, jsonb, bigint
) from public, anon;
grant execute on function public.chowk_admin_review_reporter_application_with_designation(
  bigint, text, text, text, text, boolean, jsonb, bigint
) to authenticated;
