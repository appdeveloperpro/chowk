create table if not exists public.newsroom_contributors (
  id bigint generated by default as identity primary key,
  profile_id uuid references public.profiles(id) on delete set null,
  display_name text not null check (length(trim(display_name)) between 2 and 160),
  slug text not null unique check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  contributor_type text not null check (contributor_type in ('staff', 'guest', 'reader')),
  public_bio text not null default '' check (length(public_bio) <= 2000),
  institutional_affiliation text not null default '' check (length(institutional_affiliation) <= 300),
  contact_email text not null default '' check (length(contact_email) <= 254),
  is_active boolean not null default true,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists newsroom_contributors_profile_unique
  on public.newsroom_contributors(profile_id)
  where profile_id is not null;

create table if not exists public.newsroom_content_assignments (
  id bigint generated by default as identity primary key,
  profile_id uuid not null references public.profiles(id) on delete cascade,
  contributor_id bigint references public.newsroom_contributors(id) on delete set null,
  article_type_key text not null references public.article_types(key) on update cascade on delete restrict,
  column_name text not null default '' check (length(column_name) <= 160),
  beat text not null default '' check (length(beat) <= 160),
  effective_from timestamptz not null default now(),
  effective_to timestamptz,
  is_active boolean not null default true,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (effective_to is null or effective_to > effective_from),
  unique(profile_id, article_type_key, column_name)
);

create table if not exists public.opinion_submissions (
  id bigint generated by default as identity primary key,
  display_name text not null check (length(trim(display_name)) between 2 and 160),
  email text not null check (length(trim(email)) between 5 and 254),
  phone text not null default '' check (length(phone) <= 40),
  headline text not null check (length(trim(headline)) between 8 and 240),
  pitch text not null check (length(trim(pitch)) between 20 and 5000),
  full_text text not null default '' check (length(full_text) <= 100000),
  conflict_disclosure text not null default '' check (length(conflict_disclosure) <= 5000),
  status text not null default 'submitted'
    check (status in ('submitted', 'needs_information', 'accepted', 'converted', 'rejected')),
  reviewer_id uuid references public.profiles(id) on delete set null,
  review_note text not null default '' check (length(review_note) <= 2000),
  created_article_id bigint references public.articles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.articles
