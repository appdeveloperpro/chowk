create or replace function public.chowk_org_user_has_active_content_assignment(
  target_article_type text,
  target_profile uuid default auth.uid()
)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.newsroom_content_assignments assignment
    where assignment.profile_id = coalesce(target_profile, auth.uid())
      and assignment.article_type_key = target_article_type
      and assignment.is_active
      and assignment.effective_from <= now()
      and (assignment.effective_to is null or assignment.effective_to >= now())
  );
$$;

create or replace function public.chowk_validate_constrained_content_type(
  target_article_type text,
  target_profile uuid default auth.uid()
)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select case
    when target_article_type in ('news', 'analysis', 'explainer', 'interview', 'feature')
      then true
    when target_article_type = 'opinion'
      then public.chowk_org_user_has_capability('newsroom.opinion.submit')
        or public.chowk_org_user_has_active_content_assignment('opinion', target_profile)
    when target_article_type = 'editorial'
      then public.chowk_org_user_has_capability('newsroom.editorial.submit')
    else
      exists (
        select 1
        from public.article_types type
        where type.key = target_article_type
          and type.is_active
          and not type.editorial_only
      )
  end;
$$;

create or replace function public.chowk_submit_reader_opinion(
  submitted_name text,
  submitted_email text,
  submitted_phone text default '',
  submitted_headline text default '',
  submitted_pitch text default '',
  submitted_full_text text default '',
  submitted_conflict_disclosure text default ''
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  saved_id bigint;
begin
  if length(trim(coalesce(submitted_name, ''))) < 2
     or length(trim(coalesce(submitted_email, ''))) < 5
     or length(trim(coalesce(submitted_headline, ''))) < 8
     or length(trim(coalesce(submitted_pitch, ''))) < 20
     or length(trim(coalesce(submitted_full_text, ''))) > 100000
     or length(trim(coalesce(submitted_conflict_disclosure, ''))) > 5000
     or submitted_email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' then
    raise exception 'Provide a valid reader opinion name, email, headline, and pitch'
      using errcode = '22023';
  end if;
  insert into public.opinion_submissions(
    display_name, email, phone, headline, pitch, full_text, conflict_disclosure
  ) values (
    trim(submitted_name), lower(trim(submitted_email)), trim(coalesce(submitted_phone, '')),
    trim(submitted_headline), trim(submitted_pitch), trim(coalesce(submitted_full_text, '')),
    trim(coalesce(submitted_conflict_disclosure, ''))
  ) returning id into saved_id;
  return saved_id;
end;
$$;

