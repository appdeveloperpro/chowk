create table if not exists public.zone_districts (
  id bigint generated by default as identity primary key,
  zone_id bigint not null references public.locations(id) on delete restrict,
  district_id bigint not null references public.locations(id) on delete restrict,
  valid_from timestamptz not null default clock_timestamp(),
  valid_to timestamptz,
  assigned_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  check (valid_to is null or valid_to > valid_from)
);

create unique index if not exists zone_districts_one_active_zone_per_district_idx
  on public.zone_districts(district_id) where valid_to is null;
create index if not exists zone_districts_zone_history_idx
  on public.zone_districts(zone_id, valid_from desc);

alter table public.zone_districts enable row level security;
grant select on public.zone_districts to authenticated;
grant usage, select on sequence public.zone_districts_id_seq to authenticated;

drop policy if exists "Admins view zone district history" on public.zone_districts;
create policy "Admins view zone district history"
on public.zone_districts for select to authenticated
using ((select public.chowk_has_any_role(array['admin','super_admin'])));

create or replace function public.chowk_validate_zone_district()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  zone_row public.locations%rowtype;
  district_row public.locations%rowtype;
begin
  if tg_op='UPDATE' and new.zone_id=old.zone_id and new.district_id=old.district_id then
    return new;
  end if;
  select * into zone_row from public.locations where id=new.zone_id and is_active;
  select * into district_row from public.locations where id=new.district_id and is_active;
  if zone_row.id is null or zone_row.location_type <> 'zone' then
    raise exception 'Choose an active zone' using errcode='23514';
  end if;
  if district_row.id is null or district_row.location_type <> 'district' then
    raise exception 'Choose an active district' using errcode='23514';
  end if;
  if zone_row.parent_id is null or zone_row.parent_id is distinct from district_row.parent_id then
    raise exception 'The zone and district must belong to the same state' using errcode='23514';
  end if;
  if tg_op='UPDATE' and new.district_id is distinct from old.district_id then
    raise exception 'A zone/district history row cannot be moved to another district' using errcode='23514';
  end if;
  return new;
end;
$$;

drop trigger if exists chowk_zone_districts_validate on public.zone_districts;
drop trigger if exists chowk_zone_districts_audit on public.zone_districts;
create trigger chowk_zone_districts_audit
after insert or update or delete on public.zone_districts
for each row execute function public.chowk_audit_row();

drop trigger if exists chowk_locations_validate_hierarchy on public.locations;

insert into public.zone_districts(zone_id,district_id,valid_from)
select zone.id,district.id,clock_timestamp()
from public.locations district
join public.locations zone on zone.id=district.parent_id
where district.location_type='district'
  and zone.location_type='zone'
  and zone.parent_id is not null
on conflict do nothing;

create trigger chowk_zone_districts_validate
before insert or update on public.zone_districts
for each row execute function public.chowk_validate_zone_district();

update public.locations district
set parent_id=zone.parent_id
from public.locations zone
where district.location_type='district'
  and zone.id=district.parent_id
  and zone.location_type='zone'
  and zone.parent_id is not null;

create or replace function public.chowk_validate_location_hierarchy()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  parent_type text;
begin
  if tg_op='UPDATE'
     and (
       new.parent_id is distinct from old.parent_id
       or new.location_type is distinct from old.location_type
     )
     and exists (
       select 1 from public.zone_districts mapping
       where mapping.valid_to is null
         and (
           mapping.zone_id=new.id
           or mapping.district_id=new.id
         )
     ) then
    raise exception 'End active zone/district mappings before changing the location hierarchy' using errcode='23514';
  end if;
  if new.parent_id is null then
    if new.location_type <> 'state' then
      raise exception 'Only a state can be a top-level location' using errcode='23514';
    end if;
    return new;
  end if;
  if new.parent_id=new.id then
    raise exception 'A location cannot be its own parent' using errcode='23514';
  end if;
  select location_type into parent_type
  from public.locations
  where id=new.parent_id and is_active;
  if parent_type is null then
    raise exception 'Choose an active parent location' using errcode='23514';
  end if;
  if not (
    (new.location_type in ('zone','district') and parent_type='state')
    or (new.location_type='city' and parent_type='district')
    or (new.location_type='coverage_area' and parent_type in ('district','city'))
  ) then
    raise exception 'The selected parent location has an invalid hierarchy level' using errcode='23514';
  end if;
  if tg_op='UPDATE' and exists (
    with recursive descendants(id,visited) as (
      select old.id,array[old.id]
      union all
      select child.id,descendants.visited || child.id
      from descendants
      join public.locations child on child.parent_id=descendants.id
      where not child.id=any(descendants.visited)
    )
    select 1 from descendants where id=new.parent_id
  ) then
    raise exception 'A location cannot be moved beneath one of its descendants' using errcode='23514';
  end if;
  return new;
end;
$$;

create trigger chowk_locations_validate_hierarchy
before insert or update on public.locations
for each row execute function public.chowk_validate_location_hierarchy();

create or replace function public.chowk_admin_assign_district_zone(
  target_zone bigint,
  target_district bigint
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := (select auth.uid());
  zone_row public.locations%rowtype;
  district_row public.locations%rowtype;
  current_mapping public.zone_districts%rowtype;
  mapping_id bigint;
begin
  if actor is null or not (select public.chowk_has_any_role(array['admin','super_admin'])) then
    raise exception 'Admin access required' using errcode='42501';
  end if;
  select * into zone_row from public.locations where id=target_zone and is_active for share;
  select * into district_row from public.locations where id=target_district and is_active for update;
  if zone_row.id is null or zone_row.location_type <> 'zone' then
    raise exception 'Choose an active zone' using errcode='22023';
  end if;
  if district_row.id is null or district_row.location_type <> 'district' then
    raise exception 'Choose an active district' using errcode='22023';
  end if;
  if zone_row.parent_id is null or zone_row.parent_id is distinct from district_row.parent_id then
    raise exception 'Choose a zone and district from the same state' using errcode='22023';
  end if;
  select * into current_mapping from public.zone_districts
  where district_id=target_district and valid_to is null for update;
  if current_mapping.id is not null and current_mapping.zone_id=target_zone then
    return current_mapping.id;
  end if;
  if current_mapping.id is not null then
    update public.zone_districts
    set valid_to=greatest(clock_timestamp(),valid_from + interval '1 microsecond')
    where id=current_mapping.id;
  end if;
  insert into public.zone_districts(zone_id,district_id,assigned_by)
  values(target_zone,target_district,actor)
  returning id into mapping_id;
  return mapping_id;
end;
$$;
revoke all on function public.chowk_admin_assign_district_zone(bigint,bigint) from public,anon;
grant execute on function public.chowk_admin_assign_district_zone(bigint,bigint) to authenticated;

create or replace function public.chowk_admin_end_district_zone(target_mapping bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (select auth.uid()) is null
     or not (select public.chowk_has_any_role(array['admin','super_admin'])) then
    raise exception 'Admin access required' using errcode='42501';
  end if;
  update public.zone_districts
  set valid_to=greatest(clock_timestamp(),valid_from + interval '1 microsecond')
  where id=target_mapping and valid_to is null;
  if not found then
    raise exception 'Active zone/district mapping not found' using errcode='P0002';
  end if;
end;
$$;
revoke all on function public.chowk_admin_end_district_zone(bigint) from public,anon;
grant execute on function public.chowk_admin_end_district_zone(bigint) to authenticated;

create or replace function public.chowk_user_covers_location(target_user uuid, target_location bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  with recursive target_path(id,parent_id,visited) as (
    select location.id,location.parent_id,array[location.id]
    from public.locations location
    where location.id=target_location and location.is_active
    union all
    select parent.id,parent.parent_id,target_path.visited || parent.id
    from target_path
    join public.locations parent on parent.id=target_path.parent_id and parent.is_active
    where not parent.id=any(target_path.visited)
  )
  select exists (
    select 1
    from public.user_coverage_assignments coverage
    where coverage.user_id=target_user
      and target_user=(select auth.uid())
      and coverage.valid_from<=now()
      and (coverage.valid_to is null or coverage.valid_to>now())
      and (
        coalesce(coverage.zone_id,coverage.district_id,coverage.city_id,coverage.coverage_area_id)
          = target_location
        or (
          coverage.include_descendants
          and coalesce(coverage.zone_id,coverage.district_id,coverage.city_id,coverage.coverage_area_id)
            in (select id from target_path)
        )
        or (
          coverage.include_descendants
          and coverage.zone_id is not null
          and exists (
            select 1 from public.zone_districts mapping
            where mapping.zone_id=coverage.zone_id
              and mapping.district_id in (select id from target_path)
              and mapping.valid_from<=now()
              and (mapping.valid_to is null or mapping.valid_to>now())
          )
        )
      )
  );
$$;
revoke all on function public.chowk_user_covers_location(uuid,bigint) from public,anon;
grant execute on function public.chowk_user_covers_location(uuid,bigint) to anon,authenticated;
