  add column if not exists opinion_column_name text,
  add column if not exists conflict_of_interest_disclosure text,
  add column if not exists fact_sources text,
  add column if not exists ai_use_disclosure text,
  add column if not exists opinion_review_status text,
  add column if not exists opinion_reviewer_id uuid;

