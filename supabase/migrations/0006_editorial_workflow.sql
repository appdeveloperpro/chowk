create or replace function public.chowk_record_article_workflow_event()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := (select auth.uid());
  actor_name_value text;
  actor_role text;
begin
  if new.workflow_status is distinct from old.workflow_status
     or nullif(current_setting('chowk.workflow_event_action',true),'') is not null then
    select full_name,role into actor_name_value,actor_role
    from public.profiles where id=actor;
    insert into public.article_workflow_events(
      article_id,actor_id,actor_name,actor_role,action,from_status,to_status,note
    ) values (
      new.id,actor,coalesce(actor_name_value,''),coalesce(actor_role,''),
      coalesce(nullif(current_setting('chowk.workflow_event_action',true),''),'status_updated'),
      old.workflow_status,new.workflow_status,
      coalesce(nullif(current_setting('chowk.workflow_event_note',true),''),
        'Workflow action recorded')
    );
  end if;
  return new;
end;
$$;

create trigger chowk_articles_workflow_history
after update on public.articles
for each row execute function public.chowk_record_article_workflow_event();
