create or replace function public.chowk_reporter_options()
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'states', coalesce((select jsonb_agg(to_jsonb(s) order by s.state_name)
      from public.states s where s.is_active), '[]'::jsonb),
    'rtos', coalesce((select jsonb_agg(jsonb_build_object(
      'id', r.id, 'state_id', r.state_id, 'rto_code', r.rto_code, 'city_name', r.city_name
    ) order by r.rto_code) from public.rto_offices r
      join public.states s on s.id = r.state_id where r.is_active and s.is_active), '[]'::jsonb),
    'types', coalesce((select jsonb_agg(jsonb_build_object(
      'id', t.id, 'type_code', t.type_code, 'name', t.name, 'description', t.description
    ) order by t.name) from public.reporter_types t where t.is_active), '[]'::jsonb),
    'agreement', (select jsonb_build_object(
      'version', a.version, 'sha256', a.sha256, 'document_url', a.document_url
    ) from public.reporter_agreement_versions a where a.status = 'published' limit 1),
    'service_agreement', (select jsonb_build_object(
      'version', a.version, 'sha256', a.sha256, 'document_url', a.document_url
    ) from public.reporter_service_agreement_versions a where a.status = 'published' limit 1)
  );
$$;
