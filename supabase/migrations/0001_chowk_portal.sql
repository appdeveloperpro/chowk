drop trigger if exists chowk_categories_set_updated_at on public.categories;
create trigger chowk_categories_set_updated_at
before update on public.categories
for each row execute function public.chowk_set_updated_at();

drop trigger if exists chowk_articles_set_updated_at on public.articles;
create trigger chowk_articles_set_updated_at
before update on public.articles
for each row execute function public.chowk_set_updated_at();

create or replace function public.chowk_handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name, phone, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    nullif(new.raw_user_meta_data ->> 'phone', ''),
    'subscriber'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists chowk_on_auth_user_created on auth.users;
create trigger chowk_on_auth_user_created
after insert on auth.users
for each row execute function public.chowk_handle_new_user();

create or replace function public.chowk_has_any_role(required_roles text[])
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles
    where id = (select auth.uid())
      and role = any(required_roles)
  );
$$;

revoke all on function public.chowk_has_any_role(text[]) from public;
grant execute on function public.chowk_has_any_role(text[]) to authenticated;
grant execute on function public.chowk_has_any_role(text[]) to anon;

create or replace function public.chowk_admin_set_user_role(target_user uuid, new_role text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor_role text;
  current_target_role text;
begin
  select role into actor_role
  from public.profiles
  where id = (select auth.uid());
  if actor_role is null or actor_role not in ('admin', 'super_admin') then
    raise exception 'Admin access required' using errcode = '42501';
  end if;
  if new_role not in ('subscriber', 'reporter', 'editor', 'admin', 'super_admin') then
    raise exception 'Invalid account role' using errcode = '22023';
  end if;
  select role into current_target_role
  from public.profiles
  where id = target_user;
  if current_target_role is null then
    raise exception 'Profile not found' using errcode = 'P0002';
  end if;
  if (current_target_role = 'super_admin' or new_role = 'super_admin')
      and actor_role <> 'super_admin' then
    raise exception 'Only a super admin can change super admin access' using errcode = '42501';
  end if;
  if target_user = (select auth.uid())
      and current_target_role = 'super_admin'
      and new_role <> 'super_admin'
      and (select count(*) from public.profiles where role = 'super_admin') <= 1 then
    raise exception 'Cannot remove the last super admin' using errcode = '23514';
  end if;
  update public.profiles set role = new_role where id = target_user;
end;
$$;

revoke all on function public.chowk_admin_set_user_role(uuid, text) from public, anon;
grant execute on function public.chowk_admin_set_user_role(uuid, text) to authenticated;

alter table public.profiles enable row level security;
alter table public.categories enable row level security;
alter table public.articles enable row level security;

revoke all on public.profiles from anon, authenticated;
grant select on public.profiles to authenticated;
grant update (full_name, phone) on public.profiles to authenticated;

drop policy if exists "Profiles are visible to their owner and staff" on public.profiles;
create policy "Profiles are visible to their owner and staff"
on public.profiles for select to authenticated
using (
  id = (select auth.uid())
  or (select public.chowk_has_any_role(array['admin', 'super_admin']))
);

drop policy if exists "Users can update their own contact details" on public.profiles;
create policy "Users can update their own contact details"
on public.profiles for update to authenticated
using (id = (select auth.uid()))
with check (id = (select auth.uid()));

drop policy if exists "Admins can update profile roles" on public.profiles;
create policy "Admins can update profile roles"
on public.profiles for update to authenticated
using ((select public.chowk_has_any_role(array['admin', 'super_admin'])))
with check (
  (select public.chowk_has_any_role(array['admin', 'super_admin']))
  and role in ('subscriber', 'reporter', 'editor', 'admin', 'super_admin')
);

grant select on public.categories to anon, authenticated;
grant insert, update, delete on public.categories to authenticated;
grant usage, select on sequence public.categories_id_seq to authenticated;

drop policy if exists "Active categories are public" on public.categories;
create policy "Active categories are public"
on public.categories for select to anon, authenticated
using (
  is_active
  or (select public.chowk_has_any_role(array['editor', 'admin', 'super_admin']))
);

drop policy if exists "Staff can manage categories" on public.categories;
create policy "Staff can manage categories"
on public.categories for all to authenticated
using ((select public.chowk_has_any_role(array['editor', 'admin', 'super_admin'])))
with check ((select public.chowk_has_any_role(array['editor', 'admin', 'super_admin'])));

grant select on public.articles to anon, authenticated;
grant insert, update, delete on public.articles to authenticated;
grant usage, select on sequence public.articles_id_seq to authenticated;

drop policy if exists "Published articles are public" on public.articles;
create policy "Published articles are public"
on public.articles for select to anon, authenticated
using (
  (status = 'published' and published_at is not null and published_at <= now())
  or author_id = (select auth.uid())
  or (select public.chowk_has_any_role(array['editor', 'admin', 'super_admin']))
);

drop policy if exists "Editorial staff can create articles" on public.articles;
create policy "Editorial staff can create articles"
on public.articles for insert to authenticated
with check (
  (select public.chowk_has_any_role(array['editor', 'admin', 'super_admin']))
  and author_id = (select auth.uid())
);

drop policy if exists "Editorial staff can update articles" on public.articles;
create policy "Editorial staff can update articles"
on public.articles for update to authenticated
using ((select public.chowk_has_any_role(array['editor', 'admin', 'super_admin'])))
with check ((select public.chowk_has_any_role(array['editor', 'admin', 'super_admin'])));

drop policy if exists "Admins can delete articles" on public.articles;
create policy "Admins can delete articles"
on public.articles for delete to authenticated
using ((select public.chowk_has_any_role(array['admin', 'super_admin'])));
