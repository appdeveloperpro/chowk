create or replace function public.chowk_sync_article_workflow()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.status is distinct from old.status and new.workflow_status is not distinct from old.workflow_status then
    new.workflow_status := case new.status
      when 'published' then 'published'
      when 'archived' then 'archived'
      else 'draft'
    end;
  end if;
  if new.workflow_status in ('published','scheduled') then
    new.status := 'published';
  elsif new.workflow_status='archived' then
    new.status := 'archived';
  else
    new.status := 'draft';
  end if;
  new.workflow_updated_at := now();
  return new;
end;
$$;

create trigger chowk_articles_sync_workflow
before update on public.articles
for each row execute function public.chowk_sync_article_workflow();

