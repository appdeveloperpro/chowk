create or replace function public.chowk_admin_publish_reporter_service_agreement_issue(
  target_application bigint,
  target_version text,
  target_sha256 text,
  target_document_path text,
  target_document_sha256 text
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := (select auth.uid());
  application_row public.reporter_applications%rowtype;
  agreement public.reporter_service_agreement_versions%rowtype;
  issue_id bigint;
begin
  if actor is null or not (select public.chowk_has_any_role(array['admin', 'super_admin'])) then
    raise exception 'Admin access required' using errcode = '42501';
  end if;
  select * into application_row
  from public.reporter_applications
  where id = target_application
  for update;
  if not found or application_row.status not in ('approved', 'active') then
    raise exception 'A service agreement can only be issued to an approved reporter'
      using errcode = '23514';
  end if;
  select * into agreement
  from public.reporter_service_agreement_versions
  where status = 'published'
  for share;
  if not found or agreement.template_content is null
      or agreement.version is distinct from target_version
      or agreement.sha256 is distinct from target_sha256 then
    raise exception 'The published personalized agreement changed. Reload it and preview again'
      using errcode = '23514';
  end if;
  if not exists (
    select 1 from public.reporter_organization_profile
    where id and is_verified
  ) then
    raise exception 'Verify the organization legal profile before issuing this agreement'
      using errcode = '23514';
  end if;
  if target_document_path is null
      or target_document_path !~ '^service/[0-9a-f-]{36}\.pdf$'
      or target_document_sha256 is null
      or target_document_sha256 !~ '^[a-f0-9]{64}$'
      or not exists (
        select 1 from storage.objects
        where bucket_id = 'chowk-reporter-agreements'
          and name = target_document_path
      ) then
    raise exception 'The generated service agreement PDF is missing or invalid'
      using errcode = '22023';
  end if;

  update public.reporter_service_agreement_issues
  set status = 'superseded'
  where application_id = application_row.id
    and status = 'published';

  insert into public.reporter_service_agreement_issues(
    application_id, user_id, agreement_version, agreement_sha256,
    document_storage_path, document_sha256, published_by
  ) values (
    application_row.id, application_row.user_id, agreement.version, agreement.sha256,
    target_document_path, target_document_sha256, actor
  ) returning id into issue_id;

  update public.reporter_applications set
    service_agreement_issue_id = issue_id,
    service_agreement_version = null,
    service_agreement_sha256 = null,
    service_agreement_document_url = null,
    service_agreement_signer_name = null,
    service_agreement_accepted_at = null
  where id = application_row.id;
  return issue_id;
end;
$$;
revoke all on function public.chowk_admin_publish_reporter_service_agreement_issue(
  bigint,text,text,text,text
) from public, anon;
grant execute on function public.chowk_admin_publish_reporter_service_agreement_issue(
  bigint,text,text,text,text
) to authenticated;

create or replace function public.chowk_accept_reporter_service_agreement_issue(
  target_issue bigint,
  signer_name text,
  acceptance_statement text
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  applicant uuid := (select auth.uid());
  application_row public.reporter_applications%rowtype;
  issue_row public.reporter_service_agreement_issues%rowtype;
  agreement public.reporter_service_agreement_versions%rowtype;
  acceptance_id bigint;
begin
  if applicant is null then
    raise exception 'Sign in required' using errcode = '42501';
  end if;
  select * into application_row
  from public.reporter_applications
  where user_id = applicant
  for update;
  if not found or application_row.status not in ('approved', 'active') then
    raise exception 'Only an approved reporter can accept service agreement terms'
      using errcode = '23514';
  end if;
  select * into issue_row
  from public.reporter_service_agreement_issues
  where id = target_issue
    and application_id = application_row.id
    and user_id = applicant
    and status = 'published'
  for update;
  if not found or application_row.service_agreement_issue_id is distinct from issue_row.id then
    raise exception 'No current personalized service agreement is available for your application'
      using errcode = '23514';
  end if;
  select * into agreement
  from public.reporter_service_agreement_versions
  where status = 'published'
  for share;
  if not found or agreement.template_content is null
      or agreement.version is distinct from issue_row.agreement_version
      or agreement.sha256 is distinct from issue_row.agreement_sha256 then
    raise exception 'The service agreement has changed. Contact Chowk to receive the current version'
      using errcode = '23514';
  end if;
  if length(trim(coalesce(signer_name, ''))) < 2
      or lower(trim(coalesce(signer_name, '')))
        <> lower(trim((select full_name from public.profiles where id = applicant)))
      or length(trim(coalesce(acceptance_statement, ''))) < 10 then
    raise exception 'Enter your account name and confirm that you accept the service agreement'
      using errcode = '22023';
  end if;
  if not exists (
    select 1 from storage.objects
    where bucket_id = 'chowk-reporter-agreements'
      and name = issue_row.document_storage_path
  ) then
    raise exception 'The personalized agreement PDF is unavailable. Contact Chowk before accepting'
      using errcode = '23514';
  end if;
  if exists (
    select 1 from public.reporter_service_agreement_acceptances
    where issue_id = issue_row.id
  ) then
    raise exception 'This service agreement has already been accepted'
      using errcode = '23505';
  end if;

  insert into public.reporter_service_agreement_acceptances(
    application_id, user_id, agreement_version, agreement_sha256, signer_name,
    acceptance_statement, generated_document_sha256, document_storage_path, issue_id
  ) values (
    application_row.id, applicant, issue_row.agreement_version, issue_row.agreement_sha256,
    trim(signer_name), trim(acceptance_statement), issue_row.document_sha256,
    issue_row.document_storage_path, issue_row.id
  ) returning id into acceptance_id;

  update public.reporter_applications set
    service_agreement_version = issue_row.agreement_version,
    service_agreement_sha256 = issue_row.agreement_sha256,
    service_agreement_document_url =
      '/api/reporter/service-agreement-accepted-document?acceptance_id=' || acceptance_id::text,
    service_agreement_signer_name = trim(signer_name),
    service_agreement_accepted_at = now()
  where id = application_row.id;
  return acceptance_id;
end;
$$;
revoke all on function public.chowk_accept_reporter_service_agreement_issue(
  bigint,text,text
) from public, anon;
grant execute on function public.chowk_accept_reporter_service_agreement_issue(
  bigint,text,text
) to authenticated;

create or replace function public.chowk_enforce_current_reporter_service_agreement()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  application_row public.reporter_applications%rowtype;
  agreement public.reporter_service_agreement_versions%rowtype;
  personalized_template boolean;
  accepted_current boolean;
begin
  if new.credential_type not in ('id_card', 'authority_letter') then
    return new;
  end if;
  select * into application_row
  from public.reporter_applications
  where user_id = new.subject_user_id_snapshot
    and status in ('approved', 'active');
  if not found then
    return new;
  end if;
  select * into agreement
  from public.reporter_service_agreement_versions
  where status = 'published';
  if not found then
    raise exception 'Publish a current service agreement before issuing reporter credentials'
      using errcode = '23514';
  end if;
  personalized_template := agreement.template_content is not null;
  if personalized_template then
    select exists (
      select 1
      from public.reporter_service_agreement_issues issue
      join public.reporter_service_agreement_acceptances acceptance
        on acceptance.issue_id = issue.id
       and acceptance.application_id = issue.application_id
       and acceptance.user_id = issue.user_id
       and acceptance.agreement_version = issue.agreement_version
       and acceptance.agreement_sha256 = issue.agreement_sha256
      where issue.id = application_row.service_agreement_issue_id
        and issue.application_id = application_row.id
        and issue.user_id = application_row.user_id
        and issue.status = 'published'
        and issue.agreement_version = agreement.version
        and issue.agreement_sha256 = agreement.sha256
        and acceptance.accepted_at is not null
    ) into accepted_current;
  else
    accepted_current := application_row.service_agreement_version = agreement.version
      and application_row.service_agreement_sha256 = agreement.sha256
      and application_row.service_agreement_accepted_at is not null;
  end if;
  if not accepted_current then
    raise exception 'The reporter must accept their current published service agreement before credentials can be issued'
      using errcode = '23514';
  end if;
  return new;
end;
$$;

drop trigger if exists chowk_enforce_current_reporter_service_agreement
  on public.staff_credentials;
create trigger chowk_enforce_current_reporter_service_agreement
  before insert on public.staff_credentials
  for each row execute function public.chowk_enforce_current_reporter_service_agreement();

drop policy if exists "Reporter service agreement documents are readable by recipient and admins"
  on storage.objects;
create policy "Reporter service agreement documents are readable by recipient and admins"
  on storage.objects for select to authenticated
  using (
    bucket_id = 'chowk-reporter-agreements'
    and exists (
      select 1 from public.reporter_service_agreement_issues issue
      where issue.document_storage_path = storage.objects.name
        and (
          issue.user_id = (select auth.uid())
          or (select public.chowk_has_any_role(array['admin', 'super_admin']))
        )
    )
  );

drop policy if exists "Users remove unrecorded reporter agreement acceptance documents"
  on storage.objects;
create policy "Users remove unrecorded reporter agreement acceptance documents"
  on storage.objects for delete to authenticated
  using (
    bucket_id = 'chowk-reporter-agreements'
    and split_part(name, '/', 1) = 'acceptance'
    and split_part(name, '/', 2) = (select auth.uid())::text
    and not exists (
      select 1 from public.reporter_agreement_acceptances acceptance
      where acceptance.document_storage_path = storage.objects.name
    )
    and not exists (
      select 1 from public.reporter_service_agreement_acceptances acceptance
      where acceptance.document_storage_path = storage.objects.name
    )
  );

drop policy if exists "Admins remove unregistered reporter agreement uploads" on storage.objects;
create policy "Admins remove unregistered reporter agreement uploads"
  on storage.objects for delete to authenticated
  using (
    bucket_id = 'chowk-reporter-agreements'
    and (select public.chowk_has_any_role(array['admin', 'super_admin']))
    and not exists (
      select 1 from public.reporter_agreement_versions agreement
      where agreement.storage_object_path = storage.objects.name
    )
    and not exists (
      select 1 from public.reporter_service_agreement_versions agreement
      where agreement.storage_object_path = storage.objects.name
    )
    and not exists (
      select 1 from public.reporter_agreement_acceptances acceptance
      where acceptance.document_storage_path = storage.objects.name
    )
    and not exists (
      select 1 from public.reporter_service_agreement_acceptances acceptance
      where acceptance.document_storage_path = storage.objects.name
    )
    and not exists (
      select 1 from public.reporter_service_agreement_issues issue
      where issue.document_storage_path = storage.objects.name
    )
  );
