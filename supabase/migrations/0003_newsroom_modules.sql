create or replace function public.chowk_audit_row()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  old_row jsonb;
  new_row jsonb;
  row_id text;
begin
  if tg_op <> 'INSERT' then old_row := to_jsonb(old); end if;
  if tg_op <> 'DELETE' then new_row := to_jsonb(new); end if;
  row_id := coalesce(new_row ->> 'id', old_row ->> 'id');
  insert into public.audit_logs (actor_id, action, table_name, record_id, before_data, after_data)
  values ((select auth.uid()), tg_op, tg_table_name, row_id, old_row, new_row);
  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

