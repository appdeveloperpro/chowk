create or replace function public.chowk_admin_review_reporter_application(
  target_application bigint,
  decision text,
  note text default '',
  signer_name text default '',
  signer_designation text default '',
  signature_accepted boolean default false
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := (select auth.uid());
  application_row public.reporter_applications%rowtype;
  rto public.rto_offices%rowtype;
  state_row public.states%rowtype;
  reporter_type public.reporter_types%rowtype;
  issued_number integer;
  new_code text;
begin
  if actor is null or not (select public.chowk_has_any_role(array['admin', 'super_admin'])) then
    raise exception 'Admin access required' using errcode = '42501';
  end if;
  if decision not in ('approved', 'rejected', 'needs_information') then
    raise exception 'Decision must be approved, rejected, or needs information' using errcode = '22023';
  end if;
  select * into application_row from public.reporter_applications
  where id = target_application for update;
  if not found or application_row.status not in ('pending', 'needs_information') then
    raise exception 'Only an application awaiting review can be reviewed' using errcode = '23514';
  end if;
  if decision in ('rejected', 'needs_information') and length(trim(coalesce(note, ''))) < 2 then
    raise exception 'A clear applicant-facing note is required for this decision' using errcode = '22023';
  end if;
  if decision = 'approved' then
    if not application_row.agreement_accepted or application_row.agreement_version = ''
       or application_row.agreement_sha256 is null or application_row.agreement_accepted_at is null then
      raise exception 'Applicant must accept a versioned reporter agreement' using errcode = '23514';
    end if;
    if length(trim(coalesce(signer_name, ''))) < 2
       or length(trim(coalesce(signer_designation, ''))) < 2
       or not coalesce(signature_accepted, false) then
      raise exception 'Company approver details and approval attestation are required' using errcode = '22023';
    end if;
    select * into rto from public.rto_offices where id = application_row.rto_office_id and is_active;
    select * into state_row from public.states where id = application_row.state_id and is_active;
    select * into reporter_type from public.reporter_types where id = application_row.reporter_type_id and is_active;
    if rto.id is null or state_row.id is null or reporter_type.id is null or rto.state_id <> state_row.id then
      raise exception 'Application location or reporter type is no longer active' using errcode = '23514';
    end if;
    insert into public.reporter_code_counters(rto_office_id, reporter_type_id)
    values (rto.id, reporter_type.id) on conflict do nothing;
    update public.reporter_code_counters set next_number = next_number + 1
    where rto_office_id = rto.id and reporter_type_id = reporter_type.id
    returning next_number - 1 into issued_number;
    if issued_number > 9999 then
      raise exception 'Reporter ID sequence is exhausted for this RTO and reporter type' using errcode = '22003';
    end if;
    new_code := lower(state_row.state_code || rto.rto_code || '-' || reporter_type.type_code || '-' || lpad(issued_number::text, 4, '0'));
    insert into public.reporter_profiles(user_id, reporter_code)
    values (application_row.user_id, new_code)
    on conflict (user_id) do nothing;
    if not exists (
      select 1 from public.reporter_assignments
      where user_id = application_row.user_id and effective_to is null
    ) then
      insert into public.reporter_assignments(user_id, rto_office_id, reporter_type_id, assigned_by)
      values (application_row.user_id, rto.id, reporter_type.id, actor);
    end if;
  end if;
  update public.reporter_applications
  set status = decision,
      review_note = trim(coalesce(note, '')),
      reviewed_by = actor,
      reviewed_at = now(),
      company_signer_name = case when decision = 'approved' then nullif(trim(coalesce(signer_name, '')), '') else null end,
      company_signer_designation = case when decision = 'approved' then nullif(trim(coalesce(signer_designation, '')), '') else null end,
      company_signature_accepted = decision = 'approved' and coalesce(signature_accepted, false),
      company_signed_at = case when decision = 'approved' then now() else null end,
      company_signature_statement = case when decision = 'approved'
        then 'Authorized approver attests to this application decision; this record is not a cryptographic signature.'
        else null end
  where id = target_application;
end;
$$;
revoke all on function public.chowk_admin_review_reporter_application(bigint,text,text,text,text,boolean) from public, anon;
grant execute on function public.chowk_admin_review_reporter_application(bigint,text,text,text,text,boolean) to authenticated;

create or replace function public.chowk_reporter_acknowledge_credential(
  target_credential bigint, typed_name text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  credential public.staff_credentials%rowtype;
  person public.profiles%rowtype;
  service_agreement_current boolean;
begin
  select * into credential from public.staff_credentials where id = target_credential for update;
  if not found then raise exception 'Credential not found for this account' using errcode = 'P0002'; end if;
  select * into person from public.profiles where id = (select auth.uid()) for update;
  if person.id is null or credential.subject_user_id_snapshot is distinct from person.id then
    raise exception 'Credential not found for this account' using errcode = '42501';
  end if;
  if credential.credential_type <> 'authority_letter' or credential.status <> 'pending_acceptance' then
    raise exception 'Only a pending authority letter can be acknowledged' using errcode = '23514';
  end if;
  if lower(trim(coalesce(typed_name, ''))) <> lower(trim(person.full_name)) then
    raise exception 'Type your account name exactly to acknowledge this letter' using errcode = '22023';
  end if;
  if credential.valid_until < current_date or credential.valid_from > current_date then
    raise exception 'This authority letter is outside its validity period' using errcode = '23514';
  end if;
  select exists (
    select 1
    from public.reporter_applications application
    join public.reporter_service_agreement_versions agreement
      on agreement.status = 'published'
     and agreement.version = application.service_agreement_version
     and agreement.sha256 = application.service_agreement_sha256
    where application.user_id = person.id and application.status = 'approved'
      and application.service_agreement_accepted_at is not null
  ) into service_agreement_current;
  if exists (select 1 from public.reporter_applications where user_id = person.id and status in ('approved', 'active'))
      and not service_agreement_current then
    raise exception 'Accept the current reporter service agreement before acknowledging this authority letter' using errcode = '23514';
  end if;
  update public.staff_credentials set status = 'superseded'
  where subject_user_id_snapshot = person.id and credential_type = 'authority_letter' and status = 'active';
  update public.staff_credentials set status = 'active',
    acknowledged_name = trim(typed_name), acknowledged_at = now()
  where id = target_credential;
  update public.reporter_applications set status = 'active'
  where user_id = person.id and status = 'approved';
  update public.profiles set role = 'reporter'
  where id = person.id and role = 'subscriber'
    and exists (select 1 from public.reporter_applications where user_id = person.id and status = 'active');
end;
$$;
revoke all on function public.chowk_reporter_acknowledge_credential(bigint,text) from public, anon;
grant execute on function public.chowk_reporter_acknowledge_credential(bigint,text) to authenticated;

create or replace function public.chowk_admin_issue_credential(
  target_user uuid,
  credential_kind text,
  start_date date,
  end_date date,
  signer_name text default '',
  signer_designation text default '',
  signer_address text default ''
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := (select auth.uid());
  person public.profiles%rowtype;
  reporter_code_value text;
  assignment public.reporter_assignments%rowtype;
  signer public.profiles%rowtype;
  reference_value text;
  token_value text;
  credential_status text;
  issued_id bigint;
  snapshot_scope jsonb;
  approved_application boolean;
  service_agreement_accepted boolean;
  service_agreement_version_value text;
begin
  if actor is null or not (select public.chowk_has_any_role(array['admin', 'super_admin'])) then
    raise exception 'Admin access required' using errcode = '42501';
  end if;
  select * into person from public.profiles where id = target_user;
  if person.id is null or person.role not in ('reporter', 'editor', 'moderator', 'subscriber') then
    raise exception 'Credentials require an eligible newsroom staff member' using errcode = '23514';
  end if;
  select exists (
    select 1 from public.reporter_applications
    where user_id = target_user and status in ('approved', 'active')
  ) into approved_application;
  select exists (
    select 1
    from public.reporter_applications application
    join public.reporter_service_agreement_versions agreement
      on agreement.status = 'published'
     and agreement.version = application.service_agreement_version
     and agreement.sha256 = application.service_agreement_sha256
    where application.user_id = target_user and application.status in ('approved', 'active')
      and application.service_agreement_accepted_at is not null
  ) into service_agreement_accepted;
  select service_agreement_version into service_agreement_version_value
  from public.reporter_applications
  where user_id = target_user and status in ('approved', 'active');
  if person.role = 'subscriber' and not approved_application then
    raise exception 'Only an approved reporter applicant can receive onboarding credentials' using errcode = '23514';
  end if;
  if credential_kind not in ('id_card', 'authority_letter') then
    raise exception 'Select a valid credential type' using errcode = '22023';
  end if;
  if credential_kind = 'id_card' and approved_application and not service_agreement_accepted then
    raise exception 'The reporter must accept the current service agreement before an ID card is issued' using errcode = '23514';
  end if;
  if credential_kind = 'authority_letter'
      and person.role <> 'reporter' and not approved_application then
    raise exception 'Authority letters are only issued to approved reporter applicants' using errcode = '23514';
  end if;
  if credential_kind = 'authority_letter' and approved_application and not service_agreement_accepted then
    raise exception 'The reporter must accept the current service agreement before an authority letter is issued' using errcode = '23514';
  end if;
  if start_date is null or end_date is null or end_date < start_date or end_date > start_date + 366 then
    raise exception 'Credential validity must be a valid period of no more than one year' using errcode = '22023';
  end if;
  if start_date < current_date then raise exception 'Credential start date cannot be in the past' using errcode = '22023'; end if;
  if credential_kind = 'id_card' and start_date <> current_date then
    raise exception 'ID cards must be effective from today' using errcode = '22023';
  end if;
  if credential_kind = 'authority_letter' and (
    length(trim(coalesce(signer_name, ''))) < 2 or length(trim(coalesce(signer_designation, ''))) < 2
    or length(trim(coalesce(signer_address, ''))) < 5
  ) then raise exception 'Authority letter signer name, designation and return address are required' using errcode = '22023'; end if;
  select reporter_code into reporter_code_value from public.reporter_profiles where user_id = target_user;
  select * into assignment from public.reporter_assignments
  where user_id = target_user and effective_to is null order by effective_from desc limit 1;
  if (person.role = 'reporter' or approved_application)
      and (assignment.id is null or reporter_code_value is null) then
    raise exception 'A reporter ID and current reporter assignment are required before issuing credentials' using errcode = '23514';
  end if;
  select * into signer from public.profiles where id = actor;
  snapshot_scope := case when assignment.id is not null then (
    select jsonb_build_object(
      'state_name', s.state_name, 'state_code', s.state_code,
      'rto_code', r.rto_code, 'city_name', r.city_name,
      'reporter_type', t.name, 'reporter_type_code', t.type_code
    )
    from public.rto_offices r join public.states s on s.id = r.state_id
    join public.reporter_types t on t.id = assignment.reporter_type_id
    where r.id = assignment.rto_office_id
  ) else coalesce((
    select jsonb_build_object(
      'coverage_location_id', location.id, 'coverage_name', location.name,
      'coverage_location_type', location.location_type, 'include_descendants', coverage.include_descendants
    )
    from public.user_coverage_assignments coverage
    join public.locations location on location.id = coalesce(
      coverage.zone_id, coverage.district_id, coverage.city_id, coverage.coverage_area_id
    )
    where coverage.user_id = target_user and coverage.valid_to is null
    order by coverage.valid_from desc limit 1
  ), '{}'::jsonb) end;
  reference_value := upper(case when credential_kind = 'id_card' then 'CH-ID-' else 'CH-AUTH-' end)
    || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 12));
  token_value := md5(gen_random_uuid()::text) || md5(gen_random_uuid()::text);
  credential_status := case when credential_kind = 'id_card' then 'active' else 'pending_acceptance' end;
  update public.staff_credentials set status = 'superseded'
  where subject_user_id_snapshot = target_user and credential_type = credential_kind
    and (status = 'pending_acceptance' or (credential_kind = 'id_card' and status = 'active'));
  insert into public.staff_credentials(
    user_id, subject_user_id_snapshot, credential_type, reference_code, verification_token, status,
    name_snapshot, role_snapshot, reporter_code_snapshot, scope_snapshot,
    issued_by, issued_by_name_snapshot, issued_by_role_snapshot,
    valid_from, valid_until, authorized_signer_name, authorized_signer_designation, return_address,
    service_agreement_version_snapshot
  ) values (
    target_user, target_user, credential_kind, reference_value, token_value, credential_status,
    person.full_name, case when approved_application then 'reporter' else person.role end,
    reporter_code_value, snapshot_scope,
    actor, signer.full_name, signer.role, start_date, end_date,
    nullif(trim(signer_name), ''), nullif(trim(signer_designation), ''), nullif(trim(signer_address), ''),
    case when credential_kind = 'authority_letter' then service_agreement_version_value end
  ) returning id into issued_id;
  return issued_id;
end;
$$;
