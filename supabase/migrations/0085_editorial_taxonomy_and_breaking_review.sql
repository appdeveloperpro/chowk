create or replace function public.chowk_validate_article_editorial_metadata()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := (select auth.uid());
  actor_role text;
  actor_name_value text;
  metadata_changed boolean;
begin
  select role, full_name into actor_role, actor_name_value
  from public.profiles where id = actor;

  if new.news_priority = 'routine' then
    new.breaking_review_status := 'none';
    new.breaking_review_note := '';
    new.breaking_reviewed_by := null;
    new.breaking_reviewed_at := null;
    new.breaking_expires_at := null;
  elsif tg_op = 'UPDATE'
        and new.breaking_review_status is distinct from old.breaking_review_status
        and current_setting('chow.breaking_review_update', true) is distinct from 'on' then
    raise exception 'Breaking-news approval can only be changed through the editorial review action'
      using errcode = '42501';
  end if;

  if tg_op = 'UPDATE' then
    metadata_changed :=
      row(new.content_type, new.news_priority, new.reporting_sources, new.reporting_evidence,
          new.contact_status, new.contact_notes, new.author_disclosure,
          new.breaking_review_status, new.breaking_review_note, new.breaking_reviewed_by,
          new.breaking_reviewed_at, new.breaking_expires_at)
      is distinct from
      row(old.content_type, old.news_priority, old.reporting_sources, old.reporting_evidence,
          old.contact_status, old.contact_notes, old.author_disclosure,
          old.breaking_review_status, old.breaking_review_note, old.breaking_reviewed_by,
          old.breaking_reviewed_at, old.breaking_expires_at);

    if metadata_changed then
      insert into public.article_editorial_metadata_history(
        article_id, actor_id, action, before_values, after_values
      ) values (
        new.id, actor,
        case
          when new.breaking_review_status is distinct from old.breaking_review_status
            then 'breaking_' || new.breaking_review_status
          else 'editorial_metadata_updated'
        end,
        jsonb_build_object(
          'content_type', old.content_type, 'news_priority', old.news_priority,
          'reporting_sources', old.reporting_sources, 'reporting_evidence', old.reporting_evidence,
          'contact_status', old.contact_status, 'contact_notes', old.contact_notes,
          'author_disclosure', old.author_disclosure,
          'breaking_review_status', old.breaking_review_status,
          'breaking_review_note', old.breaking_review_note,
          'breaking_expires_at', old.breaking_expires_at
        ),
        jsonb_build_object(
          'content_type', new.content_type, 'news_priority', new.news_priority,
          'reporting_sources', new.reporting_sources, 'reporting_evidence', new.reporting_evidence,
          'contact_status', new.contact_status, 'contact_notes', new.contact_notes,
          'author_disclosure', new.author_disclosure,
          'breaking_review_status', new.breaking_review_status,
          'breaking_review_note', new.breaking_review_note,
          'breaking_expires_at', new.breaking_expires_at
        )
      );

      if new.breaking_review_status is distinct from old.breaking_review_status then
        insert into public.article_workflow_events(
          article_id, actor_id, actor_name, actor_role, action, from_status, to_status, note
        ) values (
          new.id, actor, coalesce(actor_name_value, ''), coalesce(actor_role, ''),
          'breaking_' || new.breaking_review_status,
          new.workflow_status, new.workflow_status, trim(new.breaking_review_note)
        );
      end if;
    end if;

    if (
      new.workflow_status is distinct from old.workflow_status
      or metadata_changed
      or new.category_id is distinct from old.category_id
    ) and new.workflow_status in ('submitted', 'editor_review', 'scheduled', 'published') then
      if new.category_id is null or not exists (
        select 1 from public.categories
        where id = new.category_id and is_active
      ) then
        raise exception 'Choose an active primary topic category before submitting or publishing'
          using errcode = '22023';
      end if;
      if exists (
        select 1 from public.article_types
        where key = new.content_type and requires_reporting_checklist
      ) then
        if length(trim(new.reporting_sources)) < 20
           or length(trim(new.reporting_evidence)) < 20
           or new.contact_status is null then
          raise exception 'Reporting stories require source notes, evidence notes, and a response/contact status'
            using errcode = '22023';
        end if;
      end if;
      if exists (
        select 1 from public.article_types
        where key = new.content_type and requires_author_disclosure
      )
            and length(trim(new.author_disclosure)) < 10 then
        raise exception 'Opinion and editorial submissions require an author or institutional disclosure'
          using errcode = '22023';
      end if;
      if new.contact_status = 'contacted' and length(trim(new.contact_notes)) < 5 then
        raise exception 'Add a brief note about the response received when contact is marked complete'
          using errcode = '22023';
      end if;
      if new.workflow_status in ('scheduled', 'published')
         and new.news_priority = 'breaking' and (
        new.breaking_review_status <> 'approved'
        or new.breaking_expires_at is null
        or new.breaking_expires_at <= case
          when new.workflow_status = 'published' then now()
          else coalesce(new.published_at, now())
        end
      ) then
        raise exception 'An editor or publisher must approve an unexpired Breaking label before publication'
          using errcode = '42501';
      end if;
    end if;
  end if;
  return new;
end;
$$;

